def _http_json(url: str, payload: dict | None = None, timeout: float = 900.0) -> dict:
    body = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(
        url, data=body, headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        raw = response.read()
    return json.loads(raw) if raw else {}


def _spec_counters(base: str) -> dict:
    """Cumulative spec-decode counters off /metrics, summed over engines.

    Counters, not gauges, so a point's numbers are the delta across it. The
    per-position vector is labelled by draft index 0..num_speculative_tokens-1.
    """
    with urllib.request.urlopen(f"{base}/metrics", timeout=30) as response:
        text = response.read().decode()

    named = {
        "vllm:spec_decode_num_drafts_total": "drafts",
        "vllm:spec_decode_num_draft_tokens_total": "draft_tokens",
        "vllm:spec_decode_num_accepted_tokens_total": "accepted",
    }
    totals = {"drafts": 0.0, "draft_tokens": 0.0, "accepted": 0.0}
    per_pos: dict[int, float] = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        name, _, value = line.rpartition(" ")
        try:
            observed = float(value)
        except ValueError:
            continue
        metric = name.split("{", 1)[0]
        if metric in named:
            totals[named[metric]] += observed
        elif metric == "vllm:spec_decode_num_accepted_tokens_per_pos_total":
            position = re.search(r'position="(\d+)"', name)
            if position:
                index = int(position.group(1))
                per_pos[index] = per_pos.get(index, 0.0) + observed
    return {**totals, "per_pos": per_pos}


def _one_request(base: str, model_name: str, prompt: str, max_tokens: int) -> tuple:
    started = time.monotonic()
    data = _http_json(
        f"{base}/v1/chat/completions",
        {
            "model": model_name,
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": max_tokens,
            # Greedy: spec decode is lossless, so both phases must produce the
            # same tokens. That equality is the integrity check below.
            "temperature": 0.0,
        },
    )
    return time.monotonic() - started, int(data["usage"]["completion_tokens"])


def _measure(
    base: str,
    model_name: str,
    prompts: list[str],
    concurrency: int,
    max_tokens: int,
    *,
    spec: bool,
    waves: int = 8,
    min_requests: int = 24,
    warmup_requests: int = 16,
) -> dict:
    """One concurrency point: throughput, plus the acceptance delta over it.

    Sends ``waves * concurrency`` requests, cycling the prompt pool, which is
    `bench/sweep.py`'s convention. A fixed request count instead makes the
    high-concurrency points a ramp-up and a drain with no steady state in
    between: at 128 prompts and c=64 the drafted phase finished in 8s and two
    runs of the same config disagreed by 46%.
    """
    # Whole multiples of the pool, so every concurrency runs *the same
    # workload*: each prompt appears an equal number of times. aiperf gets this
    # for free from synthetic fixed-shape requests; with real prompts, a bare
    # `waves * concurrency` makes the prompt mix -- and so the mean output
    # length -- a function of concurrency, which is not a thing the engine did.
    # The floor is bench/config.py's; 8 waves is its requests_per_concurrency.
    target = max(min_requests, waves * concurrency)
    pool = len(prompts)
    requested = pool * max(1, -(-target // pool))
    warmup_count = max(warmup_requests, concurrency)
    prompts = [prompts[i % len(prompts)] for i in range(requested)]
    # NOTE: callers must hand this an already-shuffled pool. Taking a prefix of
    # a pool grouped by source makes the workload itself a function of
    # concurrency -- c<=8 drew only HumanEval+ and scored accept_len 4.0-4.3
    # against 3.92 for the mixed points above it.
    warmup = [prompts[i % len(prompts)] for i in range(warmup_count)]
    with ThreadPoolExecutor(max_workers=concurrency) as pool:
        list(pool.map(lambda p: _one_request(base, model_name, p, 32), warmup))
    # Harmless with caching disabled; kept so the point still starts cold if
    # someone turns prefix caching back on.
    _http_json(f"{base}/reset_prefix_cache", {})

    before = _spec_counters(base) if spec else None
    started = time.monotonic()
    with ThreadPoolExecutor(max_workers=concurrency) as pool:
        results = list(
            pool.map(lambda p: _one_request(base, model_name, p, max_tokens), prompts)
        )
    wall = time.monotonic() - started
    after = _spec_counters(base) if spec else None

    tokens = sum(count for _, count in results)
    point = {
        "concurrency": concurrency,
        "requests": len(results),
        "waves": round(len(results) / concurrency, 1),
        "pool_repeats": len(results) // len(set(prompts)),
        "wall_s": round(wall, 2),
        "output_tokens": tokens,
        "tok_s_gpu": round(tokens / wall, 1),
        "tok_s_user": round(sum(n / lat for lat, n in results) / len(results), 1),
        "mean_latency_s": round(sum(lat for lat, _ in results) / len(results), 2),
    }
    if before is not None and after is not None:
        drafts = after["drafts"] - before["drafts"]
        draft_tokens = after["draft_tokens"] - before["draft_tokens"]
        accepted = after["accepted"] - before["accepted"]
        point["drafts"] = int(drafts)
        point["draft_tokens"] = int(draft_tokens)
        point["accepted_tokens"] = int(accepted)
        # vLLM's convention (v1/spec_decode/metrics.py:113): the bonus token
        # counts toward the length, so a drafter that never lands scores 1.0.
        point["accept_len"] = round(1 + accepted / drafts, 3) if drafts else None
        point["accept_rate"] = (
            round(accepted / draft_tokens, 4) if draft_tokens else None
        )
        point["per_pos_rate"] = (
            [
                round(
                    (after["per_pos"].get(i, 0.0) - before["per_pos"].get(i, 0.0))
                    / drafts,
                    3,
                )
                for i in sorted(after["per_pos"])
            ]
            if drafts
            else []
        )
    return point


def _serve_target(
    serve_path: str,
    served_name: str,
    log_path: str,
    *,
    graph_ceiling: int,
    port: int,
    kv_cache_gib: float,
    max_num_seqs: int,
    max_model_len: int,
    gpu_memory_utilization: float,
):
    cmd = [
        sys.executable,
        "-m",
        "vllm.entrypoints.cli.main",
        "serve",
        # For the drafted phase this is the *drafter* checkpoint, not the
        # target: a speculators config makes vLLM swap the served model and
        # tokenizer for its own `verifier.name_or_path` and build the
        # speculative config from the checkpoint
        # (transformers_utils/config.py:740). Passing the target plus
        # --speculative-config instead would need trust_remote_code for the
        # draft's `auto_map`.
        serve_path,
        "--port",
        str(port),
        "--served-model-name",
        served_name,
        "--max-model-len",
        str(max_model_len),
        "--max-num-seqs",
        str(max_num_seqs),
        "--gpu-memory-utilization",
        str(gpu_memory_utilization),
        # Off, not on. The prompt pool repeats 2-6x within a point at high
        # concurrency, so with caching those repeats read their prefills out
        # of the cache and the high-c points score up to ~13% of their token
        # work for free relative to c<=16.
        "--no-enable-prefix-caching",
        # Both phases capture the same range, and it must cover the *drafted*
        # forward pass, which is concurrency x (1 + num_speculative_tokens)
        # rows -- not concurrency. The 512 default (compilation.py:703) is
        # exactly 64 x 8, so without this every point above c=64 silently
        # ran the draft eager while the baseline kept its graphs.
        "--compilation-config",
        json.dumps({"max_cudagraph_capture_size": graph_ceiling}),
        # Pinned off, not merely omitted. `async_scheduling` defaults to None,
        # which resolves to True unless something blocks it -- and
        # `config/vllm.py:1345` blocks it for method="dflash" only. Omitting
        # the flag therefore gives the no-draft phase an async scheduler the
        # drafted phase cannot have, which flatters the baseline.
        "--no-async-scheduling",
        # Pinned, and identical in both phases: Modal's "H100" is either an
        # 80GB HBM3 or a 94GB NVL, and letting KV float would change the
        # servable batch between the two servers being compared.
        "--kv-cache-memory-bytes",
        str(int(kv_cache_gib * 1024**3)),
        "--default-chat-template-kwargs",
        '{"enable_thinking": false}',
    ]
    # Note this makes the numbers incomparable to the reap50-1024-512 sweep,
    # which runs with async scheduling on.

    print(f"[spec] serving: {' '.join(cmd)}", flush=True)
    log = open(log_path, "w")  # noqa: SIM115
    proc = subprocess.Popen(
        cmd,
        stdout=log,
        stderr=subprocess.STDOUT,
        # /reset_prefix_cache and /server_info are dev-mode routes.
        env={**os.environ, "PYTHONUNBUFFERED": "1", "VLLM_SERVER_DEV_MODE": "1"},
    )
    return proc, log


def _server_audit(base: str) -> dict:
    """The few /server_info fields that would invalidate a phase comparison."""
    try:
        info = _http_json(f"{base}/server_info?config_format=json", timeout=60)
    except Exception as exc:  # noqa: BLE001
        return {"error": repr(exc)}
    config = info.get("vllm_config") or {}
    scheduler = config.get("scheduler_config") or {}
    cache = config.get("cache_config") or {}
    speculative = config.get("speculative_config") or {}
    return {
        "async_scheduling": scheduler.get("async_scheduling"),
        "max_num_seqs": scheduler.get("max_num_seqs"),
        "prefix_caching": cache.get("enable_prefix_caching"),
        "num_gpu_blocks": cache.get("num_gpu_blocks"),
        "spec_method": speculative.get("method"),
        "num_speculative_tokens": speculative.get("num_speculative_tokens"),
    }


@app.function(
    image=image,
    gpu=GPU,
    timeout=TIMEOUT_S,
    volumes={
        "/cache/hf": hf_cache,
        "/cache/vllm": vllm_cache,
        "/reap": reap_models,
        "/spec": spec_out,
    },
    secrets=HF_SECRETS,
)
def acceptance(
    model: str = PRUNED,
    drafter: str = DRAFTER,
    label: str = "specdec-reap50-code",
    specs: str = EVAL_SPECS,
    concurrencies: str = "1,2,4,8,16,32,48,64,80,96",
    # Requests per point are waves * concurrency, so this is wall-clock per
    # point rather than a sample size; 8 matches the aiperf sweeps.
    waves: int = 8,
    max_tokens: int = 512,
    kv_cache_gib: float = 32.0,
    # Above the top concurrency on purpose: at concurrency == max_num_seqs the
    # scheduler has zero slack, which cost ~2% in the short-128-128 sweep.
    max_num_seqs: int = 128,
    max_model_len: int = 4096,
    gpu_memory_utilization: float = 0.90,
    port: int = 8000,
    # Must match the checkpoint's speculators_config.proposal_methods[0]; it
    # sets how many rows per request the verify pass carries.
    spec_tokens: int = 7,
    # Measure the drafted phase only. The no-draft phase on the same container
    # is what makes the throughput number mean anything, so this is off.
    skip_baseline: bool = False,
) -> str:
    """Serve the REAP target with and without the drafter; report both."""
    out = f"/spec/{label}"
    os.makedirs(out, exist_ok=True)
    endpoint = f"http://localhost:{port}"
    served_name = "target"
    points = [int(c) for c in concurrencies.split(",") if c.strip()]
    # Sized from what the *scheduler* can produce, not from what the sweep
    # asks for: the batch can reach max_num_seqs requests, each carrying
    # (1 + spec_tokens) rows through the verify pass. Covering that leaves
    # headroom above the top concurrency instead of landing exactly on it,
    # so a queued or warmup batch cannot fall off the captured range.
    # Costs ~2 min of startup and some memory per extra size; if a phase OOMs
    # at capture time, drop kv_cache_gib rather than this.
    rows = max(max_num_seqs, max(points)) * (1 + spec_tokens)
    graph_ceiling = max(512, -(-rows // 16) * 16)
    print(
        f"[spec] graph ceiling {graph_ceiling} rows (max c={max(points)})",
        flush=True,
    )

    prompt_file = f"{out}/prompts.jsonl"
    rc = _stream(
        [SPEC_PY, "-c", EVAL_PROMPTS, prompt_file, *specs.split(",")],
        cwd=REMOTE_SPEC,
        label="Step 0: extract eval prompts",
    )
    if rc != 0:
        raise RuntimeError(f"prompt extraction failed, rc={rc}")
    with open(prompt_file) as fh:
        rows = [json.loads(line) for line in fh if line.strip()]
    # Interleaved, not concatenated: _measure takes a prefix of this list, so a
    # source-grouped pool would make every point below one wave of the pool a
    # different workload from the ones above it.
    random.Random(42).shuffle(rows)
    prompts = [row["prompt"] for row in rows]
    sources: dict[str, int] = {}
    for row in rows:
        sources[row["source"]] = sources.get(row["source"], 0) + 1
    print(f"[spec] {len(prompts)} prompts: {sources}", flush=True)

    phases = [("draft", drafter)]
    if not skip_baseline:
        phases.append(("no-draft", model))

    results: dict = {
        "model": model,
        "drafter": drafter,
        "prompts": len(prompts),
        "sources": sources,
        "max_tokens": max_tokens,
        "phases": {},
    }
    for name, serve_path in phases:
        proc, log = _serve_target(
            serve_path,
            served_name,
            f"{out}/server-{name}.log",
            graph_ceiling=graph_ceiling,
            port=port,
            kv_cache_gib=kv_cache_gib,
            max_num_seqs=max_num_seqs,
            max_model_len=max_model_len,
            gpu_memory_utilization=gpu_memory_utilization,
        )
        try:
            _wait_health(endpoint, proc, timeout_s=1800)
            phase: dict = {"audit": _server_audit(endpoint), "points": []}
            for concurrency in points:
                measured = _measure(
                    endpoint,
                    served_name,
                    prompts,
                    concurrency,
                    max_tokens,
                    spec=name == "draft",
                    waves=waves,
                )
                print(f"[{name}] {measured}", flush=True)
                phase["points"].append(measured)
            results["phases"][name] = phase
        finally:
            print(f"[spec] stopping {name} server", flush=True)
            proc.terminate()
            try:
                proc.wait(timeout=180)
            except subprocess.TimeoutExpired:
                proc.kill()
            log.close()

    for name, phase in results["phases"].items():
        for warning in _integrity_warnings(phase["points"]):
            print(f"[integrity] {name}: {warning}", flush=True)
            phase.setdefault("warnings", []).append(warning)

    with open(f"{out}/results.json", "w") as fh:
        json.dump(results, fh, indent=2)
    spec_out.commit()
    return _acceptance_report(results, out, label)


def _integrity_warnings(points: list[dict], min_waves: float = 4.0) -> list[str]:
    """bench/report.py's checks, applied to a phase measured here.

    Not imported from there: the container image excludes `inco/`, so this
    function is a copy. Keep the two in step.
    """
    found = []
    ordered = sorted(points, key=lambda p: p["concurrency"])
    for earlier, later in zip(ordered, ordered[1:]):
        if later["tok_s_user"] > earlier["tok_s_user"]:
            found.append(
                f"tok/s/user rose from {earlier['tok_s_user']:.1f} at c="
                f"{earlier['concurrency']} to {later['tok_s_user']:.1f} at c="
                f"{later['concurrency']}: impossible, so these points do not "
                "measure the engine"
            )
    for point in ordered:
        seen = point["requests"] / point["concurrency"]
        if seen < min_waves:
            found.append(
                f"c={point['concurrency']} saw only {seen:.1f} waves "
                f"({point['requests']} requests)"
            )
    return found


def _acceptance_report(results: dict, out: str, label: str) -> str:
    """Markdown for the two phases, plus the lossless-output check."""
    lines = [
        f"target:  {results['model']}",
        f"drafter: {results['drafter']}",
        f"prompts: {results['prompts']} {results['sources']}",
        f"max_tokens: {results['max_tokens']}, greedy",
        "",
        (
            "| phase | c | tok/s/gpu | tok/s/user | mean lat s | out tok | "
            "accept_len | accept_rate |"
        ),
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, phase in results["phases"].items():
        for point in phase["points"]:
            lines.append(
                f"| {name} | {point['concurrency']} | {point['tok_s_gpu']} | "
                f"{point['tok_s_user']} | {point['mean_latency_s']} | "
                f"{point['output_tokens']} | {point.get('accept_len', '-')} | "
                f"{point.get('accept_rate', '-')} |"
            )

    drafted = results["phases"].get("draft", {}).get("points", [])
    plain = results["phases"].get("no-draft", {}).get("points", [])
    if plain:
        lines += ["", "| c | tok/s/gpu draft | no-draft | ratio | output tokens |"]
        lines.append("|---|---|---|---|---|")
        for spec_point, base_point in zip(drafted, plain):
            ratio = spec_point["tok_s_gpu"] / base_point["tok_s_gpu"]
            # Greedy spec decode is lossless, so the two phases should emit the
            # same tokens for the same prompts. A gap means one phase truncated
            # or the sampling path differed -- read the throughput with care.
            delta = spec_point["output_tokens"] - base_point["output_tokens"]
            lines.append(
                f"| {spec_point['concurrency']} | {spec_point['tok_s_gpu']} | "
                f"{base_point['tok_s_gpu']} | {ratio:.2f}x | "
                f"{spec_point['output_tokens']} vs {base_point['output_tokens']} "
                f"({delta:+d}) |"
            )

    for name, phase in results["phases"].items():
        lines += ["", f"{name} audit: {phase['audit']}"]
        for point in phase["points"]:
            if point.get("per_pos_rate"):
                lines.append(
                    f"  c={point['concurrency']} per-position acceptance: "
                    f"{point['per_pos_rate']}"
                )

    lines += [
        "",
        f"saved to {out}/results.json",
        f"pull with: modal volume get inco-spec {label} ./inco/results/spec",
    ]
    return "\n".join(lines)
