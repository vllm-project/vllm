def _stream(cmd: list[str], *, cwd: str, label: str, env: dict | None = None) -> int:
    """Run a step, prefixing each line with elapsed minutes."""
    print(f"\n=== {label} ===\n$ {' '.join(cmd)}", flush=True)
    started = time.monotonic()
    proc = subprocess.Popen(
        cmd,
        cwd=cwd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
        env={**os.environ, "PYTHONUNBUFFERED": "1", **(env or {})},
    )
    for line in proc.stdout:
        elapsed = (time.monotonic() - started) / 60
        print(f"[{elapsed:5.1f}m] {line.rstrip()}", flush=True)
    rc = proc.wait()
    print(f"[{label}] rc={rc}", flush=True)
    return rc


def _wait_health(url: str, proc: subprocess.Popen, timeout_s: float) -> None:
    """Poll /health, aborting the moment the server process dies."""
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise RuntimeError(f"vLLM server exited early with rc={proc.returncode}")
        try:
            with urllib.request.urlopen(f"{url}/health", timeout=5) as resp:
                if resp.status == 200:
                    print("[server] ready", flush=True)
                    return
        except Exception:
            pass
        time.sleep(5)
    raise TimeoutError(f"server not ready within {timeout_s}s")


def _train_and_report(
    out, hidden, model, label, layer_ids, steps,
    epochs, lr, seq_length, block_size, max_anchors, num_layers,
) -> str:
    """Step 5 plus the run summary. Shared by the full run and --train-only."""
    # Step 5 -- train the draft on the freed GPU.
    steps.append(
        (
            "train",
            _stream(
                [
                    "/opt/spec/bin/torchrun",
                    "--standalone", "--nproc_per_node", "1",
                    "-m", "speculators.train",
                    "--verifier-name-or-path", model,
                    # --data-path is the *prepare-data* output (an Arrow
                    # dataset); the hidden states are a separate tree.
                    "--data-path", out,
                    "--hidden-states-path", hidden,
                    "--save-path", f"{out}/checkpoints",
                    "--on-missing", "raise",
                    "--epochs", str(epochs),
                    "--lr", str(lr),
                    "--total-seq-len", str(seq_length),
                    "--speculator-type", "dflash2",
                    "--block-size", str(block_size),
                    "--max-anchors", str(max_anchors),
                    "--num-layers", str(num_layers),
                    "--target-layer-ids", *layer_ids,
                ],
                cwd=REMOTE_SPEC,
                label="Step 5: train dflash2",
            ),
        )
    )

    spec_out.commit()
    hf_cache.commit()

    found = subprocess.run(
        ["find", f"{out}/checkpoints", "-maxdepth", "3"],
        capture_output=True, text=True,
    ).stdout.strip()
    summary = "\n".join(f"  {name:24} rc={rc}" for name, rc in steps)
    return (
        f"target: {model}\naux layers: {layer_ids}\n\n{summary}\n\n"
        f"checkpoints:\n{found or '  (none)'}\n\n"
        f"pull with: modal volume get inco-spec {label} ./inco/results/spec"
    )




