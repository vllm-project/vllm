"""Train a DFlash2 drafter against a REAP-pruned target on Modal.

    modal run inco/modal/modal_speculators.py

Runs the *offline* pipeline -- server up, regenerate responses, prepare data,
extract hidden states, server down, train -- which is what lets one container
do the whole run on a single GPU: the vLLM server and the trainer never need
it at the same time.

Two Python environments, because they cannot be reconciled:

  * system python  -- this fork's vLLM, which supplies the
    `extract_hidden_states` speculative method and
    `ExampleHiddenStatesConnector`.
  * `/opt/spec`    -- speculators, which pins `transformers>=5.0` and
    `torch>=2.9`; installing it over the fork would replace the engine.

They communicate over HTTP on localhost, exactly as the upstream
`examples/train/*.sh` scripts do. `docs/user_guide/tutorials/train.md`
recommends separate venvs for the same reason.

Training data is on-policy: `regenerate-responses` re-answers every prompt
with *this* checkpoint, so the draft learns the pruned model's own output
distribution rather than some other model's. `docs/user_guide/tutorials/
train.md:107` requires that; the `tutorial_regen` dataset the upstream examples
use was generated by Qwen3-8B and is wrong for this target.

Prompts come from `evol-codealpaca-v1`, the corpus REAP was calibrated on, so
the drafter is trained on the distribution the retained experts are strongest
at. `--skip-regen` falls back to an off-policy preset, which is a pipeline
check rather than a usable drafter -- see the 64-sample smoke result in
EXPERIMENTS.md.
"""

