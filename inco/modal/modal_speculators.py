def pipeline(
    model: str = PRUNED,
    label: str = "dflash2-reap50-code-5k",
    # Off-policy fallback, used only under --skip-regen: a prepare-data preset
    # name, an `hf:` spec, or a path.
    dataset: str = "ultrachat",
    # On-policy prompt source: an HF dataset id, or a local .jsonl whose rows
    # already carry a "prompt" field (then --prompt-field is ignored).
    prompt_dataset: str = CODE_PROMPTS,
    prompt_field: str = "instruction",
    # 5000 samples / 5 epochs is the upstream dflash2 recipe
    # (examples/train/dflash2_qwen3_8b_ultrachat_online_5k.sh).
    max_samples: int = 5000,
    seq_length: int = 2048,
    epochs: int = 5,
    lr: float = 3e-4,
    block_size: int = 8,
    max_anchors: int = 512,
    num_layers: int = 5,
    # 48-layer analogue of the example's "2 18 33" for Qwen3-8B's 36 layers.
    # Must match what launch_vllm.py bakes into eagle_aux_hidden_state_layer_ids.
    target_layer_ids: str = "2 24 45",
    concurrency: int = 16,
    # Regeneration is plain decoding against the target, so it runs much wider
    # than hidden-state extraction. 1024 output tokens covers the 512-token
    # serving shape with headroom for the target to run long.
    regen_concurrency: int = 64,
    regen_max_tokens: int = 1024,
    # Must exceed seq_length. prepare-data renders with
    # truncate_prompt_tokens=seq_length, and vLLM's render endpoint budgets
    # max_tokens = max_model_len - input_length. Set them equal and every
    # conversation that reaches the truncation limit renders a budget of 0,
    # which SamplingParams rejects -- a silent per-conversation data drop.
    max_model_len: int = 0,  # 0 -> 2 * seq_length
    gpu_memory_utilization: float = 0.85,
    port: int = 8000,
    # Reuse prepare-data/hidden-states already on the volume and go
    # straight to step 5. Saves re-serving the target.
    train_only: bool = False,
    # Train on an off-policy preset instead of this checkpoint's own outputs.
    skip_regen: bool = False,
) -> str:
    out = f"/spec/{label}"
    hidden = f"{out}/hidden_states"
    os.makedirs(out, exist_ok=True)
    layer_ids = target_layer_ids.split()
    max_model_len = max_model_len or 2 * seq_length
    endpoint = f"http://localhost:{port}"
    prompts = f"{out}/prompts.jsonl"
    regen = f"{out}/regen.jsonl"
    # regenerate-responses writes boundary rows (input_ids + loss_mask), which
    # prepare-data passes through instead of re-rendering.
    train_data = dataset if skip_regen else regen

    # Fail loudly here rather than 20 minutes into a server start.
    import importlib.util

    if importlib.util.find_spec("vllm") is None:
        raise RuntimeError(
            f"this function must run under the fork's interpreter, but "
            f"sys.executable={sys.executable} has no vllm"
        )
    print(f"[spec] engine python: {sys.executable}", flush=True)
    print(f"[spec] target={model}\n[spec] out={out}", flush=True)

    steps: list[tuple[str, int]] = []
    if train_only:
        print("[spec] train_only: reusing existing data on the volume", flush=True)
        return _train_and_report(
            out, hidden, model, label, layer_ids, steps,
            epochs, lr, seq_length, block_size, max_anchors, num_layers,
        )

    # Step 0 -- the prompt set. Ahead of the server because a wrong dataset id
    # or field name should cost seconds, not a 5-minute weight load.
    if not skip_regen:
        rc = _stream(
            [SPEC_PY, "-c", PROMPT_EXTRACT, prompt_dataset, prompt_field,
             str(max_samples), prompts],
            cwd=REMOTE_SPEC,
            label="Step 0: extract prompts",
        )
        steps.append(("prompts", rc))
        if rc != 0:
            raise RuntimeError(f"prompt extraction failed, rc={rc}")

    # Step 1 -- vLLM server, under the *fork's* interpreter.
    # Not a context manager: the handle has to outlive this statement and is
    # closed in the finally below, once the server is down.
    server_log = open(f"{out}/server.log", "w")  # noqa: SIM115
    server = subprocess.Popen(
        [
            sys.executable,
            f"{REMOTE_SPEC}/scripts/launch_vllm.py",
            model,
            "--target-layer-ids",
            *layer_ids,
            "--hidden-states-path",
            hidden,
            "--",
            "--port",
            str(port),
            "--gpu-memory-utilization",
            str(gpu_memory_utilization),
            "--max-model-len",
            str(max_model_len),
        ],
        cwd=REMOTE_SPEC,
        stdout=server_log,
        stderr=subprocess.STDOUT,
        env={**os.environ, "PYTHONUNBUFFERED": "1"},
    )

    try:
        _wait_health(endpoint, server, timeout_s=1800)

        # Step 1b -- on-policy responses from the target itself. Failing hard
        # here matters: without it prepare-data would silently fall through to
        # whatever `dataset` points at and train the draft on the wrong
        # distribution. --resume lets an interrupted file be continued.
        if not skip_regen:
            rc = _stream(
                [
                    SPEC_CLI, "regenerate-responses",
                    "--endpoint", f"{endpoint}/v1/chat/completions",
                    # Doubles as the tokenizer path for the review-only `text`
                    # twin, so it must be the checkpoint, not a served alias.
                    "--model", model,
                    "--dataset", prompts,
                    "--limit", str(max_samples),
                    "--concurrency", str(regen_concurrency),
                    "--max-tokens", str(regen_max_tokens),
                    "--outfile", regen,
                    "--resume",
                    "--seed", "42",
                    # Qwen3 non-thinking defaults, from the model card.
                    "--sampling-params",
                    json.dumps({"temperature": 0.7, "top_p": 0.8, "top_k": 20}),
                ],
                cwd=REMOTE_SPEC,
                label="Step 1b: regenerate-responses",
            )
            steps.append(("regenerate", rc))
            if rc != 0:
                raise RuntimeError(f"regeneration failed, rc={rc}")

        # Step 2 -- to speculator format. Regenerated rows arrive as
        # input_ids + loss_mask and pass straight through; an off-policy
        # preset is rendered through the target's chat template instead.
        steps.append(
            (
                "prepare-data",
                _stream(
                    [
                        SPEC_CLI, "prepare-data",
                        "--model", model,
                        "--data", train_data,
                        "--render-endpoint", endpoint,
                        "--max-samples", str(max_samples),
                        "--output", out,
                        "--seq-length", str(seq_length),
                    ],
                    cwd=REMOTE_SPEC,
                    label="Step 2: prepare-data",
                ),
            )
        )

        # Step 3 -- the part that actually exercises the pruned target: aux
        # hidden states at layers 2/24/45 pulled out through the connector.
        steps.append(
            (
                "generate-offline-data",
                _stream(
                    [
                        SPEC_CLI, "generate-offline-data",
                        "--preprocessed-data", out,
                        "--endpoint", f"{endpoint}/v1",
                        "--output", hidden,
                        "--max-samples", str(max_samples),
                        "--concurrency", str(concurrency),
                        "--validate-outputs",
                    ],
                    cwd=REMOTE_SPEC,
                    label="Step 3: generate-offline-data",
                ),
            )
        )
    finally:
        print("\n=== Step 4: stopping server ===", flush=True)
        server.terminate()
        try:
            server.wait(timeout=120)
        except subprocess.TimeoutExpired:
            server.kill()
        server_log.close()

    return _train_and_report(
        out, hidden, model, label, layer_ids, steps,
        epochs, lr, seq_length, block_size, max_anchors, num_layers,
    )


