"""Generate the per-dtype translation units of the softplus-sqrt topk kernel.

Instantiating topkGatingSoftplusSqrtKernelLauncher is by far the most expensive
part of building _moe_C_stable_libtorch: per (gating dtype, topk_indices dtype,
hash index dtype) the launcher emits one kernel per expert count (15), per warp
size (2), per compile-time `use_hash` value (2), i.e. ~1900 device kernels for
the full cross product. In a single translation unit they serialize ~100 s of
AMDGPU code generation onto one core, which makes that file the critical path of
a whole-ROCm build.

This script emits from the single VARIANTS list below:

  * topk_softplus_sqrt_launch_<variant>.cu: one translation unit per variant,
    instantiating only its own slice of the kernel set so ninja compiles the
    slices in parallel,
  * topk_softplus_sqrt_launch_entries.inc: the prototypes of the entry points
    those translation units define (included at file scope by
    topk_softplus_sqrt_kernels.cu),
  * topk_softplus_sqrt_dispatch.inc: the dtype dispatch on gating_output and
    topk_indices (included inside topk_softplus_sqrt()).

The datatype pairs, their at::ScalarType counterparts and the dispatch order are
all derived from VARIANTS, so adding a variant is a one-line change here and no
hand-written prototype/dispatch entry can go stale.

Generated files are written next to the kernels, like
csrc/quantization/marlin/generate_kernels.py, and are gitignored.
"""

import glob
import hashlib
import os
import sys

# MD5 of this script, recorded in the stamp so CMake can tell whether the files
# on disk were produced by the current version (same value as `file(MD5 ...)`).
with open(__file__, "rb") as _self:
    SCRIPT_HASH = hashlib.md5(_self.read()).hexdigest()
STAMP_NAME = ".topk_softplus_sqrt_generated"

# One entry per generated translation unit.
#   name:                 suffix of the generated file / entry point
#   gating_type:          C++ type of gating_output (aliases for the half types
#                         live in topk_softplus_sqrt_kernels.cuh so that the
#                         generated code stays CUDA/HIP agnostic, hence the
#                         fully qualified spellings)
#   gating_scalar_type:   matching at::ScalarType
#   indices_type:         C++ type of topk_indices
#   indices_scalar_type:  matching at::ScalarType
VARIANTS = [
    {
        "name": "f32_i32",
        "gating_type": "float",
        "gating_scalar_type": "Float",
        "indices_type": "int",
        "indices_scalar_type": "Int",
    },
    {
        "name": "f32_u32",
        "gating_type": "float",
        "gating_scalar_type": "Float",
        "indices_type": "uint32_t",
        "indices_scalar_type": "UInt32",
    },
    {
        "name": "f32_i64",
        "gating_type": "float",
        "gating_scalar_type": "Float",
        "indices_type": "int64_t",
        "indices_scalar_type": "Long",
    },
    {
        "name": "f16_i32",
        "gating_type": "vllm::moe::TopkGatingHalf",
        "gating_scalar_type": "Half",
        "indices_type": "int",
        "indices_scalar_type": "Int",
    },
    {
        "name": "f16_u32",
        "gating_type": "vllm::moe::TopkGatingHalf",
        "gating_scalar_type": "Half",
        "indices_type": "uint32_t",
        "indices_scalar_type": "UInt32",
    },
    {
        "name": "f16_i64",
        "gating_type": "vllm::moe::TopkGatingHalf",
        "gating_scalar_type": "Half",
        "indices_type": "int64_t",
        "indices_scalar_type": "Long",
    },
    {
        "name": "bf16_i32",
        "gating_type": "vllm::moe::TopkGatingBFloat16",
        "gating_scalar_type": "BFloat16",
        "indices_type": "int",
        "indices_scalar_type": "Int",
    },
    {
        "name": "bf16_u32",
        "gating_type": "vllm::moe::TopkGatingBFloat16",
        "gating_scalar_type": "BFloat16",
        "indices_type": "uint32_t",
        "indices_scalar_type": "UInt32",
    },
    {
        "name": "bf16_i64",
        "gating_type": "vllm::moe::TopkGatingBFloat16",
        "gating_scalar_type": "BFloat16",
        "indices_type": "int64_t",
        "indices_scalar_type": "Long",
    },
]

OUTPUT_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(
    os.path.abspath(__file__))

FILE_HEAD = """\
// auto generated by generate_topk_softplus_sqrt.py
// clang-format off
"""

TU_HEAD = FILE_HEAD + """
#include "topk_softplus_sqrt_kernels.cuh"

namespace vllm {
namespace moe {
"""

TU_TAIL = """
}  // namespace moe
}  // namespace vllm
"""

# One entry point per variant. It owns the (gating dtype, topk_indices dtype)
# slice of the kernel set; the hash index dtype remains a runtime property of
# input_ids/tid2eid (int or int64), as does the hash/image/plain code path.
TU_ENTRY = """
void topk_softplus_sqrt_launch_{name}(const {gating_type}* gating_output,
                                      {indices_type}* topk_indices,
                                      const TopkSoftplusSqrtParams& p) {{
  if (p.tid2eid != nullptr) {{
    if (p.ids_are_int64) {{
      topkGatingSoftplusSqrtKernelLauncher<{indices_type}, {gating_type},
                                           int64_t>(
          gating_output, p.topk_weights, topk_indices, p.token_expert_indices,
          p.num_tokens, p.num_experts, p.topk, p.renormalize,
          p.routed_scaling_factor, p.correction_bias, /*use_hash=*/true,
          static_cast<const int64_t*>(p.input_ids),
          static_cast<const int64_t*>(p.tid2eid), p.stream, p.is_padding,
          p.bias_vl, p.image_sentinel_lo);
    }} else {{
      topkGatingSoftplusSqrtKernelLauncher<{indices_type}, {gating_type}, int>(
          gating_output, p.topk_weights, topk_indices, p.token_expert_indices,
          p.num_tokens, p.num_experts, p.topk, p.renormalize,
          p.routed_scaling_factor, p.correction_bias, /*use_hash=*/true,
          static_cast<const int*>(p.input_ids),
          static_cast<const int*>(p.tid2eid), p.stream, p.is_padding,
          p.bias_vl, p.image_sentinel_lo);
    }}
  }} else if (p.bias_vl != nullptr) {{
    // Non-hash rows with bias_vl: image tokens select experts by score +
    // bias_vl, so input_ids drives the per-row branch and its dtype drives the
    // hash-index instantiation.
    if (p.ids_are_int64) {{
      topkGatingSoftplusSqrtKernelLauncher<{indices_type}, {gating_type},
                                           int64_t>(
          gating_output, p.topk_weights, topk_indices, p.token_expert_indices,
          p.num_tokens, p.num_experts, p.topk, p.renormalize,
          p.routed_scaling_factor, p.correction_bias, /*use_hash=*/false,
          static_cast<const int64_t*>(p.input_ids),
          static_cast<const int64_t*>(nullptr), p.stream, p.is_padding,
          p.bias_vl, p.image_sentinel_lo);
    }} else {{
      topkGatingSoftplusSqrtKernelLauncher<{indices_type}, {gating_type}, int>(
          gating_output, p.topk_weights, topk_indices, p.token_expert_indices,
          p.num_tokens, p.num_experts, p.topk, p.renormalize,
          p.routed_scaling_factor, p.correction_bias, /*use_hash=*/false,
          static_cast<const int*>(p.input_ids),
          static_cast<const int*>(nullptr), p.stream, p.is_padding,
          p.bias_vl, p.image_sentinel_lo);
    }}
  }} else {{
    topkGatingSoftplusSqrtKernelLauncher<{indices_type}, {gating_type}>(
        gating_output, p.topk_weights, topk_indices, p.token_expert_indices,
        p.num_tokens, p.num_experts, p.topk, p.renormalize,
        p.routed_scaling_factor, p.correction_bias, /*use_hash=*/false,
        static_cast<const {indices_type}*>(nullptr),
        static_cast<const {indices_type}*>(nullptr), p.stream, p.is_padding,
        nullptr, 0);
  }}
}}
"""

ENTRIES_HEAD = FILE_HEAD + """
// Prototypes of the entry points defined in the generated
// topk_softplus_sqrt_launch_*.cu translation units.

namespace vllm {
namespace moe {
"""

ENTRIES_ENTRY = """
void topk_softplus_sqrt_launch_{name}(const {gating_type}* gating_output,
                                      {indices_type}* topk_indices,
                                      const TopkSoftplusSqrtParams& p);
"""

ENTRIES_TAIL = """
}  // namespace moe
}  // namespace vllm
"""

DISPATCH_HEAD = FILE_HEAD + """
  // Dispatch on the runtime dtypes of gating_output and topk_indices, two
  // nested levels mirroring the two template parameters of the generated entry
  // points.
  const auto gating_scalar_type = gating_output.scalar_type();
  const auto indices_scalar_type = topk_indices.scalar_type();
"""

DISPATCH_TAIL = """  else {
    STD_TORCH_CHECK(false, "Unsupported gating_output data type: ",
                    gating_scalar_type);
  }
"""


def group_by_gating_type():
    # Insertion order is the order of the generated if/else-if chain, i.e. the
    # VARIANTS order is the dispatch priority.
    groups = {}
    for variant in VARIANTS:
        groups.setdefault(
            (variant["gating_scalar_type"], variant["gating_type"]),
            []).append(variant)
    return groups


def generate_tu(variant):
    return (TU_HEAD + TU_ENTRY.format(**variant) + TU_TAIL)


def generate_entries():
    body = "".join(ENTRIES_ENTRY.format(**v) for v in VARIANTS)
    return ENTRIES_HEAD + body + ENTRIES_TAIL


def generate_dispatch():
    lines = [DISPATCH_HEAD.rstrip("\n")]
    groups = list(group_by_gating_type().items())
    for index, ((gating_scalar_type, gating_type), variants) in enumerate(groups):
        keyword = "if" if index == 0 else "else if"
        lines.append(
            f"  {keyword} (gating_scalar_type ==\n"
            f"      torch::headeronly::ScalarType::{gating_scalar_type}) {{")
        lines.append(
            f"    const {gating_type}* gating_ptr = static_cast<"
            f"const {gating_type}*>(gating_output.const_data_ptr());")
        for inner_index, variant in enumerate(variants):
            inner_keyword = "if" if inner_index == 0 else "else if"
            lines.append(
                f"    {inner_keyword} (indices_scalar_type ==\n"
                f"        torch::headeronly::ScalarType::"
                f"{variant['indices_scalar_type']}) {{")
            lines.append(
                f"      topk_softplus_sqrt_launch_{variant['name']}(\n"
                f"          gating_ptr, topk_indices.mutable_data_ptr<"
                f"{variant['indices_type']}>(), params);")
            lines.append("    }")
        lines.append("""    else {
      STD_TORCH_CHECK(false, "Unsupported topk_indices data type: ",
                      indices_scalar_type);
    }""")
        lines.append("  }")
    lines.append(DISPATCH_TAIL.rstrip("\n"))
    return "\n".join(lines) + "\n"


def remove_old_files():
    for path in glob.glob(
            os.path.join(OUTPUT_DIR, "topk_softplus_sqrt_launch_*.cu")):
        os.remove(path)
    for name in ("topk_softplus_sqrt_launch_entries.inc",
                 "topk_softplus_sqrt_dispatch.inc"):
        path = os.path.join(OUTPUT_DIR, name)
        if os.path.exists(path):
            os.remove(path)


def write(name, content):
    with open(os.path.join(OUTPUT_DIR, name), "w") as fd:
        fd.write(content)


def main():
    remove_old_files()
    outputs = []
    for variant in VARIANTS:
        name = f"topk_softplus_sqrt_launch_{variant['name']}.cu"
        write(name, generate_tu(variant))
        outputs.append(name)
    for name, content in (("topk_softplus_sqrt_launch_entries.inc",
                           generate_entries()),
                          ("topk_softplus_sqrt_dispatch.inc",
                           generate_dispatch())):
        write(name, content)
        outputs.append(name)
    # Record what is on disk next to the outputs: CMake checks this list instead
    # of trusting a glob, so a deleted unit is noticed, and the stamp lives in the
    # source tree (not in a per-build-directory cache) because the outputs do.
    write(STAMP_NAME, SCRIPT_HASH + "\n" + "\n".join(outputs) + "\n")
    print(f"Generated {len(outputs)} softplus-sqrt topk files.")


if __name__ == "__main__":
    main()
