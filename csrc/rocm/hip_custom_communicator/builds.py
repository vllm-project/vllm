import json
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

FIELDS = (
    "algorithm",
    "block_x",
    "block_y",
    "block_z",
    "waves_per_eu",
    "tile_m",
    "tile_n",
    "tile_k",
    "quantization",
    "pack_bytes",
)
WAVE_SIZE = 64
PACK_BYTES = 16
WORLDS = (2, 4, 8)
DTYPES = ("f16", "bf16")
WEIGHT_DTYPE = "f32"
CPP_TYPES = {"f16": "c10::Half", "bf16": "c10::BFloat16", "f32": "float"}
SCALAR_TYPES = {"f16": "Half", "bf16": "BFloat16", "f32": "Float"}
QUANTIZATIONS = {"exact": "Quantization::exact", "int4": "Quantization::int4"}
ALGORITHM_ENUMS = {
    "all_reduce": "AllReduceAlgorithm",
    "all_reduce_add_rms_norm": "AllReduceAddRmsNormKernelAlgorithm",
    "all_reduce_add_attn_res_rms_norm": "AllReduceAddAttnResRmsNormAlgorithm",
    "add_rms_norm": "AddRmsNormAlgorithm",
    "add_attn_res_rms_norm": "AddAttnResRmsNormAlgorithm",
}
SPLIT_ROWS = {
    "all_reduce_add_rms_norm": "add_rms_norm",
    "all_reduce_add_attn_res_rms_norm": "add_attn_res_rms_norm",
}
TEMPLATE_ARGS = {
    "all_reduce": "algorithm quantize_int4 T world tile_m tile_n block_x wave_size "
    "pack_bytes waves_per_eu contiguous tail",
    "all_reduce_add_rms_norm": "algorithm residual quantize_int4 T W world tile_m "
    "tile_n block_x wave_size pack_bytes waves_per_eu chunked tail",
    "all_reduce_add_attn_res_rms_norm": "algorithm quantize_int4 T world tile_m "
    "tile_n tile_k block_x wave_size pack_bytes waves_per_eu chunked tail",
    "add_rms_norm": "residual T W tile_m tile_n block_x wave_size pack_bytes "
    "waves_per_eu chunked",
    "add_attn_res_rms_norm": "T tile_m tile_n tile_k block_x wave_size "
    "pack_bytes waves_per_eu chunked",
}
HEADERS = (
    "kernels/all_reduce.cuh",
    "kernels/all_reduce_add_attn_res_rms_norm.cuh",
    "kernels/all_reduce_add_rms_norm.cuh",
)
GENERATED = "// GENERATED by csrc/rocm/hip_custom_communicator/builds.py. Do not edit."


@dataclass(frozen=True)
class Command:
    table: Path
    out: Path
    archs: tuple[str, ...]


@dataclass(frozen=True)
class Build:
    kernel: str
    algorithm: str
    block_x: int
    block_y: int
    block_z: int
    waves_per_eu: int
    tile_m: int
    tile_n: int
    tile_k: int
    quantization: str
    pack_bytes: int

    def file_name(self) -> str:
        return (
            f"hip_custom_communicator_{self.kernel}_{self.algorithm}__{self.block_x}x"
            f"{self.block_y}x{self.block_z}_w{self.waves_per_eu}_t{self.tile_m}x"
            f"{self.tile_n}x{self.tile_k}_{self.quantization}_p{self.pack_bytes}.hip"
        )


@dataclass(frozen=True)
class Instance:
    build: Build
    world: int
    dtype: str
    weight_dtype: str
    contiguous: bool
    chunked: bool
    tail: bool
    quantize_int4: bool
    residual: bool
    wave_size: int = WAVE_SIZE

    def template(self) -> str:
        b = self.build
        value = {
            "algorithm": f"{ALGORITHM_ENUMS[b.kernel]}::{b.algorithm}",
            "quantize_int4": str(self.quantize_int4).lower(),
            "T": CPP_TYPES[self.dtype],
            "W": CPP_TYPES[self.weight_dtype],
            "world": str(self.world),
            "tile_m": str(b.tile_m),
            "tile_n": str(b.tile_n),
            "tile_k": str(b.tile_k),
            "block_x": str(b.block_x),
            "wave_size": str(self.wave_size),
            "pack_bytes": str(b.pack_bytes),
            "waves_per_eu": str(b.waves_per_eu),
            "contiguous": str(self.contiguous).lower(),
            "chunked": str(self.chunked).lower(),
            "tail": str(self.tail).lower(),
            "residual": str(self.residual).lower(),
        }
        args = ", ".join(value[a] for a in TEMPLATE_ARGS[b.kernel].split())
        return f"{b.kernel}<{args}>"


@dataclass(frozen=True)
class Generated:
    build: Build
    instances: tuple[Instance, ...]


def parse_args(argv: list[str]) -> Command:
    if len(argv) != 3:
        raise SystemExit(__doc__)
    table, out, archs = argv
    return Command(
        Path(table),
        Path(out),
        tuple(a for a in archs.replace(",", ";").split(";") if a),
    )


def config_builds(config: dict) -> list[Build]:
    if not str(config["algorithm"]).endswith("_split"):
        return [Build(config["kernel"], *(config[f] for f in FIELDS))]
    body = {**config, "algorithm": config["algorithm"].removesuffix("_split")}
    second = SPLIT_ROWS[config["kernel"]]
    fields = {
        f: config.get(f"{second}_{f}", 1)
        for f in FIELDS
        if f not in ("algorithm", "quantization")
    }
    return [
        Build("all_reduce", *(body[f] for f in FIELDS)),
        Build(
            second,
            *(
                {**fields, "algorithm": "rows", "quantization": "exact"}[f]
                for f in FIELDS
            ),
        ),
    ]


def parse_table(path: Path) -> dict[str, list[Build]]:
    out: dict[str, list[Build]] = {}
    for arch, table in json.loads(path.read_text()).items():
        builds = out.setdefault(arch, [])
        for config in table["configs"]:
            kernel = config["kernel"]
            if kernel not in ALGORITHM_ENUMS:
                raise SystemExit(f"{path}: {arch}: no kernel {kernel}")
            for build in config_builds(config):
                if (
                    "tile_k" not in TEMPLATE_ARGS[build.kernel].split()
                    and build.tile_k != 1
                ):
                    raise SystemExit(f"{path}: {arch}: {build}: its kernel has no K")
                if build not in builds:
                    builds.append(build)
    return out


def instances(build: Build) -> list[Instance]:
    params = TEMPLATE_ARGS[build.kernel].split()
    int4 = build.quantization == "int4" and build.pack_bytes == PACK_BYTES
    two_shot = build.algorithm.startswith("two_shot")
    plain = build.kernel == "all_reduce"
    tails = ((True, True), (False, True)) if int4 else ((False, int4),)
    residuals = (True, False) if "residual" in params else (False,)
    out: list[Instance] = []
    for dtype in DTYPES:
        for world in WORLDS if "world" in params else (0,):
            for weight in (dtype, WEIGHT_DTYPE) if "W" in params else (dtype,):
                for contiguous in (True, False) if plain and two_shot else (False,):
                    for chunked in (False,) if plain else (True, False):
                        for tail, quantize_int4 in tails:
                            for residual in residuals:
                                out.append(
                                    Instance(
                                        build,
                                        world,
                                        dtype,
                                        weight,
                                        contiguous,
                                        chunked,
                                        tail,
                                        quantize_int4,
                                        residual,
                                    )
                                )
    return out


def generate(builds: list[Build]) -> list[Generated]:
    return [Generated(b, tuple(instances(b))) for b in builds]


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def emit(generated: list[Generated], out: Path) -> None:
    out_dir = out.parent
    rows: dict[str, list[Instance]] = {}
    held: dict[str, str] = {}
    files: list[tuple[Build, list[Instance]]] = []
    manifest: dict[str, list[dict]] = {}
    for g in generated:
        kernel_rows = rows.setdefault(g.build.kernel, [])
        kernel_rows += [i for i in g.instances if i not in kernel_rows]
        new = list(
            {i.template(): i for i in g.instances if i.template() not in held}.values()
        )
        held.update((i.template(), g.build.file_name()) for i in new)
        if new:
            files.append((g.build, new))
        for name in dict.fromkeys(held[i.template()] for i in g.instances):
            if asdict(g.build) not in manifest.setdefault(name, []):
                manifest[name].append(asdict(g.build))

    tables = [
        GENERATED,
        "// Each kernel's instance table, a row for every compiled instance.",
        "",
    ]
    for kernel, kernel_rows in rows.items():
        name = "k" + "".join(w.capitalize() for w in kernel.split("_")) + "Instances"
        tables.append(f"inline const Instance<{ALGORITHM_ENUMS[kernel]}> {name}[] = {{")
        for i in kernel_rows:
            b = i.build
            tables.append(
                f"    {{.algorithm = {ALGORITHM_ENUMS[kernel]}::{b.algorithm}, "
                f".block_x = {b.block_x}, .block_y = {b.block_y}, "
                f".block_z = {b.block_z}, .waves_per_eu = {b.waves_per_eu}, "
                f".tile_m = {b.tile_m}, .tile_n = {b.tile_n}, .tile_k = {b.tile_k}, "
                f".quantization = {QUANTIZATIONS[b.quantization]}, "
                f".pack_bytes = {b.pack_bytes}, .world = {i.world}, "
                f".wave_size = {i.wave_size}, "
                f".dtype = at::ScalarType::{SCALAR_TYPES[i.dtype]}, "
                f".weight_dtype = at::ScalarType::{SCALAR_TYPES[i.weight_dtype]}, "
                f".contiguous = {str(i.contiguous).lower()}, "
                f".chunked = {str(i.chunked).lower()}, "
                f".tail = {str(i.tail).lower()}, "
                f".quantize_int4 = {str(i.quantize_int4).lower()}, "
                f".residual = {str(i.residual).lower()},\n"
                f"     .kernel = reinterpret_cast<void*>(&{i.template()})}},"
            )
        tables += ["};", ""]
    write(out, "\n".join(tables))

    declared = [
        GENERATED,
        "// Every kernel instance, compiled in its build's own file; declared here so",
        "// the host instantiates none.",
        f"static_assert(kPackBytes == {PACK_BYTES}, \"builds.py's widest pack is not "
        "the host's\");",
        "static_assert(kWorlds == std::array<int, 3>{"
        + ", ".join(map(str, WORLDS))
        + "}, \"builds.py's worlds are not the host's\");",
        "static_assert(kDtypes == std::array<at::ScalarType, 2>{"
        + ", ".join(f"at::ScalarType::{SCALAR_TYPES[d]}" for d in DTYPES)
        + "}, \"builds.py's dtypes are not the host's\");",
        "",
    ]
    for build, compiled in files:
        body = [
            f"{GENERATED} {build}",
            "#include <c10/util/BFloat16.h>",
            "#include <c10/util/Half.h>",
            "#include <hip/hip_runtime.h>",
            "",
            *(f'#include "hip_custom_communicator/{h}"' for h in HEADERS),
            "",
            "namespace hip_custom_communicator {",
            *(
                f"template __global__ decltype({i.template()}) {i.template()};"
                for i in compiled
            ),
            "}  // namespace hip_custom_communicator",
            "",
        ]
        write(out_dir / build.file_name(), "\n".join(body))
        declared += [
            f"extern template __global__ decltype({i.template()}) {i.template()};"
            for i in compiled
        ]
    write(out_dir / "hip_custom_communicator_instances.inc", "\n".join(declared) + "\n")
    write(
        out_dir / "hip_custom_communicator_instances.txt",
        "".join(build.file_name() + "\n" for build, _ in files),
    )
    write(
        out_dir / "hip_custom_communicator_instances.json",
        json.dumps(manifest, indent=1) + "\n",
    )


def main() -> None:
    command = parse_args(sys.argv[1:])
    tables = parse_table(command.table)
    generated: list[Generated] = []
    for arch in command.archs:
        generated += generate(tables.get(arch, []))
    emit(generated, command.out)


if __name__ == "__main__":
    main()
