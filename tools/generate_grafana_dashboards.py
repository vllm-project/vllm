def queries(dashboard: JSON) -> Iterator[str]:
    """All PromQL queries of a dashboard's panels and variables."""
    for panel in dashboard["panels"]:
        for p in [panel, *panel.get("panels", [])]:
            yield from (t["expr"] for t in p.get("targets", []))
    for variable in dashboard["templating"]["list"]:
        if variable["type"] == "query":
            yield variable["query"]


def defined_metrics() -> set[str]:
    """Return the metric names defined in vllm/, e.g. "vllm:prompt_tokens"."""
    names: set[str] = set()
    for path in (REPO_ROOT / "vllm").rglob("*.py"):
        names.update(re.findall(r"[\"'](vllm:\w+)[\"']", path.read_text("utf-8")))
    return names


def undefined_metrics(dashboard: JSON, defined: set[str]) -> list[str]:
    """Return the vLLM metrics a dashboard queries that are not defined."""
    # Exposition adds suffixes to the defined names of counters and histograms.
    suffixes = ("_total", "_bucket", "_count", "_sum")
    return sorted(
        name
        for name in set(re.findall(r"vllm:\w+", " ".join(queries(dashboard))))
        if {name, *(name.removesuffix(s) for s in suffixes)}.isdisjoint(defined)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the vLLM dashboards.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the checked-in dashboards differ from the generated ones.",
    )
    args = parser.parse_args()

    errors = []
    defined = defined_metrics()
    for filename, build in DASHBOARDS.items():
        path = OUTPUT_DIR / filename
        dashboard = build()
        if undefined := undefined_metrics(dashboard, defined):
            errors.append(f"{filename} queries undefined vLLM metrics: {undefined}")
        content = json.dumps(dashboard, indent=2, ensure_ascii=False) + "\n"
        if not args.check:
            path.write_text(content, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != content:
            errors.append(
                f"{path.relative_to(REPO_ROOT)} is out of date. "
                f"Run: python tools/{Path(__file__).name}"
            )
    unknown = sorted({p.name for p in OUTPUT_DIR.glob("*.json")} - set(DASHBOARDS))
    if unknown:
        errors.append(f"Dashboards not produced by this script: {unknown}")
    for error in errors:
        print(error)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
