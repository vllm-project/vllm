def per_engine(
    title: str,
    description: str,
    expr: Callable[[str], str],
    *,
    by: str = "instance, engine",
    unit: str = "short",
    max_value: float | None = None,
) -> JSON:
    """One series per engine (or instance), for spotting outliers."""
    legend = "{{instance}} · engine {{engine}}" if "engine" in by else "{{instance}}"
    return timeseries(
        title,
        description,
        [target(expr(by), legend)],
        unit=unit,
        max_value=max_value,
        legend="table",
    )


