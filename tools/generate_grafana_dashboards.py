def target(
    expr: str,
    legend: str = "__auto",
    *,
    instant: bool = False,
    fmt: str = "time_series",
) -> JSON:
    """A query of the panel's data source. Grafana defaults to range queries."""
    query: JSON = {"expr": expr, "legendFormat": legend}
    if fmt != "time_series":
        query["format"] = fmt
    if instant:
        query |= {"instant": True, "range": False}
    return query


def thresholds(*steps: tuple[str, float | None]) -> JSON:
    return {
        "mode": "absolute",
        "steps": [{"color": color, "value": value} for color, value in steps],
    }


NEUTRAL = thresholds(("blue", None))
# Lower is better (error ratios, saturation).
LOW_IS_GOOD = {
    "ratio": thresholds(("green", None), ("orange", 0.001), ("red", 0.01)),
    "kv": thresholds(("green", None), ("orange", 0.9), ("red", 0.98)),
    "rate": thresholds(("green", None), ("orange", 0.001), ("red", 1)),
    "count": thresholds(("green", None), ("red", 1)),
}
# Higher is better (SLO attainment).
SLO = thresholds(("red", None), ("orange", 0.9), ("green", 0.99))


def color_override(name: str, color: str) -> JSON:
    return {
        "matcher": {"id": "byName", "options": name},
        "properties": [
            {"id": "color", "value": {"fixedColor": color, "mode": "fixed"}}
        ],
    }


def _panel(kind: str, title: str, description: str, targets: list[JSON]) -> JSON:
    for i, t in enumerate(targets):
        t["refId"] = chr(ord("A") + i)
    return {
        "type": kind,
        "title": title,
        "description": description,
        "datasource": DATASOURCE,
        "targets": targets,
    }


def timeseries(
    title: str,
    description: str,
    targets: list[JSON],
    *,
    unit: str = "short",
    max_value: float | None = None,
    stack: bool = False,
    legend: str = "list",
    colors: dict[str, str] | None = None,
    decimals: int | None = None,
    log_scale: bool = False,
) -> JSON:
    """A time series panel. `legend` is "list", "table" or "hidden".

    Panels without a legend show a single series, drawn in a fixed color.
    """
    custom: JSON = {
        "fillOpacity": 25 if stack else 10,
        "lineWidth": 1,
        "showPoints": "never",
    }
    if stack:
        custom["stacking"] = {"group": "A", "mode": "normal"}
    if log_scale:
        custom["scaleDistribution"] = {"log": 10, "type": "log"}
    color = (
        {"fixedColor": "blue", "mode": "fixed"}
        if legend == "hidden"
        else {"mode": "palette-classic"}
    )
    defaults: JSON = {"color": color, "custom": custom, "unit": unit}
    if not log_scale:
        defaults["min"] = 0
    if max_value is not None:
        defaults["max"] = max_value
    if decimals is not None:
        defaults["decimals"] = decimals
    panel = _panel("timeseries", title, description, targets)
    panel["fieldConfig"] = {
        "defaults": defaults,
        "overrides": [color_override(k, v) for k, v in (colors or {}).items()],
    }
    panel["options"] = {
        "legend": {
            "calcs": ["mean", "max", "lastNotNull"] if legend == "table" else [],
            "displayMode": "table" if legend == "table" else "list",
            "placement": "bottom",
            "showLegend": legend != "hidden",
        },
        "tooltip": {"mode": "multi", "sort": "desc"},
    }
    return panel


def stat(
    title: str,
    description: str,
    expr: str,
    *,
    unit: str,
    steps: JSON = NEUTRAL,
    decimals: int | None = None,
    ratio: bool = False,
) -> JSON:
    """A stat tile showing the latest value with a sparkline.

    Tiles colored by thresholds carry a judgement; neutral tiles do not.
    `ratio` tiles divide by request counts, so no data means no traffic.
    """
    defaults: JSON = {
        "color": {"mode": "thresholds"},
        "mappings": [NO_TRAFFIC],
        "thresholds": steps,
        "unit": unit,
    }
    if decimals is not None:
        defaults["decimals"] = decimals
    if ratio:
        defaults["noValue"] = "No traffic"
    panel = _panel("stat", title, description, [target(expr)])
    panel["fieldConfig"] = {"defaults": defaults, "overrides": []}
    panel["options"] = {
        "colorMode": "none" if steps is NEUTRAL else "value",
        "graphMode": "area",
        "justifyMode": "auto",
        "orientation": "auto",
        "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
        "textMode": "value",
    }
    return panel


def heatmap(title: str, description: str, expr: str, *, unit: str) -> JSON:
    """A heatmap of a Prometheus histogram's buckets over time."""
    panel = _panel(
        "heatmap", title, description, [target(expr, "{{le}}", fmt="heatmap")]
    )
    panel["options"] = {
        "calculate": False,
        "cellGap": 1,
        "color": {
            "exponent": 0.5,
            "fill": "blue",
            "mode": "scheme",
            "reverse": False,
            "scale": "exponential",
            "scheme": "Blues",
            "steps": 64,
        },
        "filterValues": {"le": 1e-9},
        "legend": {"show": True},
        "rowsFrame": {"layout": "auto"},
        "tooltip": {"mode": "single", "showColorScale": False, "yHistogram": True},
        "yAxis": {"axisPlacement": "left", "unit": unit},
    }
    return panel


def distribution(title: str, description: str, q: Promql, histogram: str) -> JSON:
    """The share of observations per histogram bucket over the time range."""
    expr = divide(
        f"sum by (le) (increase({q.sel(f'{histogram}_bucket')}[$__range]))",
        f"sum(increase({q.sel(f'{histogram}_count')}[$__range]))",
        "on () group_left ()",
    )
    panel = _panel(
        "bargauge",
        title,
        description,
        [target(expr, "{{le}}", instant=True, fmt="heatmap")],
    )
    # Label each bar by its bucket's upper bound, e.g. "1000.0" -> "≤ 1000".
    panel["transformations"] = [
        {
            "id": "renameByRegex",
            "options": {"regex": r"^([\d.]+?)(\.0)?$", "renamePattern": "≤ $1"},
        }
    ]
    panel["fieldConfig"] = {
        "defaults": {
            "color": {"fixedColor": "blue", "mode": "fixed"},
            "decimals": 0,
            "min": 0,
            "unit": "percentunit",
        },
        "overrides": [],
    }
    panel["options"] = {
        "displayMode": "basic",
        "namePlacement": "auto",
        "orientation": "vertical",
        "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
        "showUnfilled": False,
        "sizing": "auto",
        "valueMode": "text",
    }
    return panel


def table(
    title: str,
    description: str,
    labels: dict[str, str],
    columns: list[tuple[str, str, str]],
    *,
    column_overrides: list[JSON] | None = None,
    sort_by: str | None = None,
) -> JSON:
    """A table joining one instant query per column on label columns.

    `labels` maps each label the queries aggregate by to its column name, and
    each column is a (name, PromQL, unit) tuple.
    """
    targets = [target(expr, instant=True, fmt="table") for _, expr, _ in columns]
    panel = _panel("table", title, description, targets)
    values = {
        f"Value #{chr(ord('A') + i)}": name for i, (name, _, _) in enumerate(columns)
    }
    rename = labels | values
    order = list(labels) + list(values)
    panel["transformations"] = [
        {"id": "merge", "options": {}},
        {
            "id": "organize",
            "options": {
                "excludeByName": {"Time": True},
                "indexByName": {name: i for i, name in enumerate(order)},
                "renameByName": rename,
            },
        },
    ]
    overrides = [
        {
            "matcher": {"id": "byName", "options": name},
            "properties": [{"id": "custom.minWidth", "value": 260 if i == 0 else 160}],
        }
        for i, name in enumerate(labels.values())
    ]
    overrides += [
        {
            "matcher": {"id": "byName", "options": name},
            "properties": [{"id": "unit", "value": unit}],
        }
        for name, _, unit in columns
    ]
    panel["fieldConfig"] = {
        "defaults": {
            "custom": {
                "align": "auto",
                "cellOptions": {"type": "auto"},
                "minWidth": 80,
            },
            "mappings": [NO_TRAFFIC],
        },
        "overrides": overrides + (column_overrides or []),
    }
    panel["options"] = {
        "cellHeight": "sm",
        "footer": {"show": False},
        "showHeader": True,
        "sortBy": [{"desc": True, "displayName": sort_by}] if sort_by else [],
    }
    return panel


def info_table(
    title: str, description: str, expr: str, columns: dict[str, str]
) -> JSON:
    """A table of an info-style metric's labels.

    `columns` maps the labels to show, in order, to their column names.
    """
    panel = _panel(
        "table", title, description, [target(expr, instant=True, fmt="table")]
    )
    panel["transformations"] = [
        {"id": "filterFieldsByName", "options": {"include": {"names": list(columns)}}},
        {
            "id": "organize",
            "options": {
                "indexByName": {name: i for i, name in enumerate(columns)},
                "renameByName": columns,
            },
        },
    ]
    panel["fieldConfig"] = {
        "defaults": {"custom": {"align": "auto", "cellOptions": {"type": "auto"}}},
        "overrides": [],
    }
    panel["options"] = {
        "cellHeight": "sm",
        "footer": {"show": False},
        "showHeader": True,
    }
    return panel


