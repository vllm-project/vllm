def _by(labels: str) -> str:
    return f" by ({labels}) " if labels else ""


def divide(numerator: str, denominator: str, matching: str = "") -> str:
    """Divide two vectors, dropping series whose denominator is zero.

    Without the filter idle periods and unused features produce NaN series.
    """
    op = f" {matching} " if matching else " "
    return f"{numerator} /{op}({denominator} > 0)"


class Promql:
    """PromQL snippets scoped by a dashboard's label selector."""

    def __init__(self, selector: str):
        self.selector = selector

    def sel(self, metric: str, *matchers: str) -> str:
        return f"{metric}{{{', '.join((self.selector, *matchers))}}}"

    def rate(self, metric: str, *matchers: str, window: str = RATE) -> str:
        return f"rate({self.sel(metric, *matchers)}[{window}])"

    def sum_rate(
        self, metric: str, *matchers: str, by: str = "", window: str = RATE
    ) -> str:
        return f"sum{_by(by)}({self.rate(metric, *matchers, window=window)})"

    def agg(self, op: str, metric: str, *matchers: str, by: str = "") -> str:
        return f"{op}{_by(by)}({self.sel(metric, *matchers)})"

    def ratio(
        self,
        numerator: str,
        denominator: str,
        *matchers: str,
        by: str = "",
        window: str = RATE,
    ) -> str:
        num = self.sum_rate(numerator, *matchers, by=by, window=window)
        return divide(num, self.sum_rate(denominator, *matchers, by=by, window=window))

    def share(self, metric: str, matcher: str, by: str = "", window: str = RATE) -> str:
        """The share of a counter's rate contributed by series matching `matcher`."""
        part = self.sum_rate(metric, matcher, by=by, window=window)
        return divide(part, self.sum_rate(metric, by=by, window=window))

    def quantile(
        self, q: float, histogram: str, by: str = "", window: str = RATE
    ) -> str:
        labels = f"le, {by}" if by else "le"
        rate = self.rate(f"{histogram}_bucket", window=window)
        return f"histogram_quantile({q}, sum by ({labels}) ({rate}))"

    def mean(self, histogram: str, by: str = "", window: str = RATE) -> str:
        return self.ratio(
            f"{histogram}_sum", f"{histogram}_count", by=by, window=window
        )


