def state_timeline(
    title: str,
    description: str,
    targets: list[JSON],
    states: dict[str, tuple[str, str]],
) -> JSON:
    """A state timeline. `states` maps each value to a (text, color) pair."""
    panel = _panel("state-timeline", title, description, targets)
    panel["fieldConfig"] = {
        "defaults": {
            # With threshold colors the timeline would show threshold ranges
            # instead of the mapped states.
            "color": {"fixedColor": "text", "mode": "fixed"},
            "mappings": [
                {
                    "type": "value",
                    "options": {
                        value: {"color": color, "index": i, "text": text}
                        for i, (value, (text, color)) in enumerate(states.items())
                    },
                }
            ],
        },
        "overrides": [],
    }
    panel["options"] = {
        "alignValue": "left",
        "legend": {"displayMode": "list", "placement": "bottom", "showLegend": True},
        "mergeValues": True,
        "rowHeight": 0.8,
        "showValue": "never",
        "tooltip": {"mode": "single", "sort": "none"},
    }
    return panel


def latency(
    title: str,
    description: str,
    q: Promql,
    histogram: str,
    *,
    unit: str = "s",
    quantiles: tuple[float, ...] = (0.5, 0.95, 0.99),
) -> JSON:
    """Percentiles and mean of a histogram, aggregated over the selection."""
    targets = [
        target(q.quantile(quantile, histogram), f"p{round(quantile * 100)}")
        for quantile in quantiles
    ]
    targets.append(target(q.mean(histogram), "mean"))
    return timeseries(title, description, targets, unit=unit, colors=QUANTILE_COLORS)


