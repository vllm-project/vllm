class Layout:
    """Places panels left to right on Grafana's 24-column grid."""

    def __init__(self) -> None:
        self.panels: list[JSON] = []
        self._next_id = 1
        self._x = 0
        self._y = 0
        self._line_height = 0
        self._collapsed_row: JSON | None = None

    def _new_id(self) -> int:
        self._next_id += 1
        return self._next_id - 1

    def _newline(self) -> None:
        self._y += self._line_height
        self._x = 0
        self._line_height = 0

    def row(self, title: str, *, collapsed: bool = False) -> None:
        """Start a row. Panels of a collapsed row are hidden until expanded."""
        if self._collapsed_row is not None:
            # Collapsed panels take no space, so the next row follows directly.
            self._y = self._collapsed_row["gridPos"]["y"] + 1
            self._x = 0
            self._line_height = 0
        else:
            self._newline()
        row: JSON = {
            "type": "row",
            "title": title,
            "collapsed": collapsed,
            "gridPos": {"h": 1, "w": GRID_WIDTH, "x": 0, "y": self._y},
            "id": self._new_id(),
            "panels": [],
        }
        self.panels.append(row)
        self._y += 1
        self._collapsed_row = row if collapsed else None

    def add(self, panel: JSON, w: int, h: int) -> None:
        if self._x + w > GRID_WIDTH:
            self._newline()
        panel["gridPos"] = {"h": h, "w": w, "x": self._x, "y": self._y}
        panel["id"] = self._new_id()
        self._x += w
        self._line_height = max(self._line_height, h)
        if self._collapsed_row is not None:
            self._collapsed_row["panels"].append(panel)
        else:
            self.panels.append(panel)


def datasource_variable() -> JSON:
    return {
        "current": {},
        "hide": 0,
        "includeAll": False,
        "label": "Data source",
        "multi": False,
        "name": "datasource",
        "options": [],
        "query": "prometheus",
        "refresh": 1,
        "regex": "",
        "type": "datasource",
    }


def query_variable(name: str, label: str, label_name: str, selector: str) -> JSON:
    """A multi-value variable listing the values of a vLLM engine label."""
    metric = "vllm:num_requests_running"
    query = f"label_values({metric}{{{selector}}}, {label_name})"
    if not selector:
        query = f"label_values({metric}, {label_name})"
    return {
        "current": {"selected": True, "text": ["All"], "value": ["$__all"]},
        "datasource": DATASOURCE,
        "definition": query,
        "hide": 0,
        "includeAll": True,
        "label": label,
        "multi": True,
        "name": name,
        "options": [],
        "query": query,
        "refresh": 2,
        "regex": "",
        "sort": 1,
        "type": "query",
    }


def custom_variable(
    name: str, label: str, options: list[tuple[str, str]], default: str
) -> JSON:
    """A single-value variable; `options` is a list of (text, value) pairs."""
    text = dict((v, t) for t, v in options)[default]
    return {
        "current": {"selected": True, "text": text, "value": default},
        "description": "",
        "hide": 0,
        "includeAll": False,
        "label": label,
        "multi": False,
        "name": name,
        "options": [
            {"selected": v == default, "text": t, "value": v} for t, v in options
        ],
        "query": ", ".join(f"{t} : {v}" for t, v in options),
        "type": "custom",
    }


