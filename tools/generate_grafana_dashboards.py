def drilldown_url(uid: str, **variables: str) -> str:
    """A data link to another vLLM dashboard keeping the time range and scope."""
    params = ["${datasource:queryparam}", "${job:queryparam}"]
    params += [f"var-{name}={value}" for name, value in variables.items()]
    params.append("${__url_time_range}")
    return f"/d/{uid}?{'&'.join(params)}"


