"""gfx950 Gluon kernels for three large-M block32 MXFP8 GEMM tiles.

``rocm_block32_gemm._launch`` runs these instead of ``_block32_tiled_kernel``
for the wq_b, wo_b and engram tiles of DeepSeek-V4.1-Flash at TP2 when the
output is BF16 and 8192 < M <= 16384 (see ``_gfx950_prefill`` there). They
store BF16 unconditionally.

* ``_block32_mixed_kernel`` (wq_b, N=16384, K=1280) splits each 128x256 tile
  into two independent 64-row programs. The activation is staged in LDS by
  double-buffered async copies, one K128 interval at a time, consumed as two
  ordered K64 scaled-MFMA steps. The weight is repacked on every call into
  32x32 panels in the scaled-MFMA operand order and loaded straight into
  registers; activation scales are repacked so one dword holds a row's four
  K-scales.
* ``_block32_output_kernel`` (wo_b and engram) stages both operands with
  single-buffered async copies while the previous step's MFMA runs, reads
  four weight scales per dword and the activation scales from a per-call
  repacked layout. The engram shape keeps the tiled kernel's four-by-eight
  tile grouping.

Like ``_block32_tiled_kernel``, every output element accumulates its scaled K
steps in ascending order in FP32, and the outputs match it bit for bit. No
packed copy outlives the call. The kernels and their launch code were
generated by GEAK-EVO.
"""

import importlib
from typing import TYPE_CHECKING

import torch

from vllm.triton_utils import gl, gluon, tl, triton

if TYPE_CHECKING:
    from .rocm_block32_gemm import _Config

# Load the AMD Gluon modules explicitly instead of relying on ``gl`` to do so.
amd = importlib.import_module(f"{gl.__name__}.amd")
cdna4 = importlib.import_module(f"{amd.__name__}.cdna4")
async_copy = importlib.import_module(f"{cdna4.__name__}.async_copy")

AMDMFMALayout = amd.AMDMFMALayout
BlockedLayout = gl.BlockedLayout
DistributedLinearLayout = gl.DistributedLinearLayout
DotOperandLayout = gl.DotOperandLayout
SliceLayout = gl.SliceLayout
SwizzledSharedLayout = gl.SwizzledSharedLayout
buffer_load = cdna4.buffer_load
buffer_store = cdna4.buffer_store
compute_efficient_padded_shared_layout = cdna4.compute_efficient_padded_shared_layout
get_mfma_scale_layout = cdna4.get_mfma_scale_layout
mfma_scaled = cdna4.mfma_scaled


@triton.constexpr_function
def _copy_layout(shared, shape, warps):
    lg = warps.bit_length() - 1
    return DistributedLinearLayout(
        reg_bases=shared.offset_bases[:4] + shared.offset_bases[10 + lg :],
        lane_bases=shared.offset_bases[4:10],
        warp_bases=shared.offset_bases[10 : 10 + lg],
        block_bases=[],
        shape=shape,
    )


@gluon.jit(do_not_specialize=["M"])
def _block32_mixed_kernel(
    X,
    XS,
    W,
    WS,
    OUT,
    M,
    N: gl.constexpr,
    K: gl.constexpr,
    stride_om,
    LOGICAL_BM: gl.constexpr,
    BN: gl.constexpr,
    BK: gl.constexpr,
    N_FIRST: gl.constexpr,
    WARPS: gl.constexpr,
    INSTR: gl.constexpr,
):
    # Independent M64/N256 owners consume two ordered native K64 steps per
    # K128 staging interval. Current weights and scales are packed per call.
    BM: gl.constexpr = LOGICAL_BM // 2
    TILE_K: gl.constexpr = BK
    TILE_N: gl.constexpr = BN
    if N_FIRST:
        pn, pm = gl.program_id(0), gl.program_id(1)
    else:
        pm, pn = gl.program_id(0), gl.program_id(1)
    MM: gl.constexpr = AMDMFMALayout(
        version=4,
        instr_shape=[INSTR, INSTR, 128 if INSTR == 16 else 64],
        transposed=True,
        warps_per_cta=[WARPS // 2, 2],
    )
    AL: gl.constexpr = DotOperandLayout(0, MM, 16)
    BL: gl.constexpr = DotOperandLayout(1, MM, 16)
    ASL: gl.constexpr = get_mfma_scale_layout(AL, [BM, TILE_K // 32])
    BSL: gl.constexpr = get_mfma_scale_layout(BL, [TILE_N, TILE_K // 32])
    SHARED_A: gl.constexpr = compute_efficient_padded_shared_layout(
        AL, [BM, TILE_K], gl.float8e4nv
    )
    LOAD: gl.constexpr = _copy_layout(SHARED_A, [BM, TILE_K], WARPS)
    rm = gl.arange(0, BM, layout=SliceLayout(1, LOAD))
    rn = gl.arange(0, TILE_N, layout=SliceLayout(0, BL))
    rk = gl.arange(0, TILE_K, layout=SliceLayout(0, LOAD))
    wk = gl.arange(0, TILE_K, layout=SliceLayout(1, BL))
    am = gl.arange(0, BM, layout=SliceLayout(1, ASL))
    ak = gl.arange(0, TILE_K // 32, layout=SliceLayout(0, ASL))
    bn = gl.arange(0, TILE_N, layout=SliceLayout(1, BSL))
    bk = gl.arange(0, TILE_K // 32, layout=SliceLayout(0, BSL))
    X += pm * BM * K
    W += pn * TILE_N * K
    XS += pm * BM * (K // 32)
    WS += pn * (TILE_N // 32) * (K // 32)
    rows_left = M - pm * BM
    xp = rm[:, None] * K + rk[None, :]
    # Weight payload is repacked per call into 32-row by 32-K panels. The two
    # 16-byte halves follow the native scaled-MFMA operand lane distribution.
    wp = (
        ((rn[None, :] // 32) * (K // 32) + wk[:, None] // 32) * 1024
        + ((wk[:, None] % 32) // 16) * 512
        + (rn[None, :] % 32) * 16
        + wk[:, None] % 16
    )
    wp = gl.max_contiguous(gl.multiple_of(wp, (16, 1)), (16, 1))
    ax_buf = gl.allocate_shared_memory(gl.float8e4nv, [2, BM, TILE_K], SHARED_A)
    async_copy.buffer_load_to_shared(ax_buf.index(0), X, xp, rm[:, None] < rows_left)
    async_copy.commit_group()
    acc = gl.full((BM, TILE_N), 0, gl.float32, MM)
    for kk in range(K // TILE_K - 1):
        b = buffer_load(W, wp + kk * TILE_K * 32)
        pa = buffer_load(
            XS.to(gl.pointer_type(gl.uint32)),
            (am // 32) * (K // 4) + kk * 32 + am % 32,
            am < rows_left,
            0,
        )
        sa = ((pa[:, None] >> (ak[None, :] * 8)) & 255).to(gl.uint8)
        pb = buffer_load(
            WS.to(gl.pointer_type(gl.uint32)), (bn // 32) * (K // 128) + kk
        )
        sb = ((pb[:, None] >> (bk[None, :] * 8)) & 255).to(gl.uint8)
        async_copy.wait_group(0)
        gl.barrier()
        aa = async_copy.load_shared_relaxed(ax_buf.index(kk % 2), AL)
        async_copy.buffer_load_to_shared(
            ax_buf.index((kk + 1) % 2),
            X,
            xp + (kk + 1) * TILE_K,
            rm[:, None] < rows_left,
        )
        async_copy.commit_group()
        acc = mfma_scaled(aa, sa, "e4m3", b, sb, "e4m3", acc)
    b = buffer_load(W, wp + (K // TILE_K - 1) * TILE_K * 32)
    pa = buffer_load(
        XS.to(gl.pointer_type(gl.uint32)),
        (am // 32) * (K // 4) + (K // TILE_K - 1) * 32 + am % 32,
        am < rows_left,
        0,
    )
    sa = ((pa[:, None] >> (ak[None, :] * 8)) & 255).to(gl.uint8)
    pb = buffer_load(
        WS.to(gl.pointer_type(gl.uint32)), (bn // 32) * (K // 128) + (K // TILE_K - 1)
    )
    sb = ((pb[:, None] >> (bk[None, :] * 8)) & 255).to(gl.uint8)
    async_copy.wait_group(0)
    gl.barrier()
    aa = async_copy.load_shared_relaxed(ax_buf.index((K // TILE_K - 1) % 2), AL)
    acc = mfma_scaled(aa, sa, "e4m3", b, sb, "e4m3", acc)
    STORE: gl.constexpr = BlockedLayout([1, 8], [4, 16], [WARPS, 1], [1, 0])
    out = gl.convert_layout(acc.to(gl.bfloat16), STORE)
    om = gl.arange(0, BM, layout=SliceLayout(1, STORE))
    on = gl.arange(0, TILE_N, layout=SliceLayout(0, STORE))
    buffer_store(
        out,
        OUT + pm * BM * stride_om + pn * TILE_N,
        om[:, None] * stride_om + on[None, :],
        om[:, None] < rows_left,
    )


@gluon.jit
def _pack_weight(
    W, P, XS, PS, M, N: gl.constexpr, K: gl.constexpr, BLOCK: gl.constexpr
):
    offset = gl.program_id(0) * BLOCK + gl.arange(
        0, BLOCK, layout=BlockedLayout([16], [64], [4], [0])
    )
    nblock = offset // (K * 32)
    within = offset % (K * 32)
    kb = within // 1024
    n = nblock * 32 + (within % 512) // 16
    k = kb * 32 + (within % 1024) // 512 * 16 + within % 16
    woff = gl.max_contiguous(gl.multiple_of(n * K + k, 16), 16)
    w = gl.load(W + woff, mask=offset < N * K, other=0.0)
    gl.store(P + offset, w, mask=offset < N * K)
    scale_size = gl.cdiv(M, 32) * K
    if gl.program_id(0) * BLOCK < scale_size:
        mb = offset // K
        within_s = offset % K
        # Four adjacent K scales form one dword for a row.
        sm = mb * 32 + (within_s % 128) // 4
        sk = (within_s // 128) * 4 + within_s % 4
        xs = gl.load(
            XS + sm * (K // 32) + sk, mask=(offset < scale_size) & (sm < M), other=0
        )
        gl.store(PS + offset, xs, mask=offset < scale_size)


@triton.jit
def _pack_output_scale(XS, PS, M, K: tl.constexpr):
    # Mask the non-power-of-two scale width used by the engram family.
    rm = tl.program_id(0) * 32 + tl.arange(0, 32)
    sk = tl.arange(0, triton.next_power_of_2(K // 32))
    value = tl.load(
        XS + rm[:, None] * (K // 32) + sk[None, :],
        mask=(rm[:, None] < M) & (sk[None, :] < K // 32),
        other=0,
    )
    po = (
        (rm[:, None] // 32) * K
        + (sk[None, :] // 2) * 64
        + (sk[None, :] % 2) * 32
        + rm[:, None] % 32
    )
    tl.store(PS + po, value, mask=sk[None, :] < K // 32)


@gluon.jit(do_not_specialize=["M"])
def _block32_output_kernel(
    X,
    XS,
    W,
    WS,
    OUT,
    M,
    N: gl.constexpr,
    K: gl.constexpr,
    stride_om,
    BM: gl.constexpr,
    BN: gl.constexpr,
    BK: gl.constexpr,
    N_FIRST: gl.constexpr,
    WARPS: gl.constexpr,
    INSTR: gl.constexpr,
):
    if N_FIRST:
        pn, pm = gl.program_id(0), gl.program_id(1)
    else:
        pm, pn = gl.program_id(0), gl.program_id(1)
    if N_FIRST and N == 12800 and K == 6144:
        grid_n: gl.constexpr = N // BN
        grid_m = gl.num_programs(1)
        linear = pm * grid_n + pn
        first_m = (linear // (4 * grid_n)) * 4
        group_m = gl.minimum(grid_m - first_m, 4)
        within = linear % (4 * grid_n)
        first_n = (within // (group_m * 8)) * 8
        group_n = gl.minimum(grid_n - first_n, 8)
        pm = first_m + (within % (group_m * 8)) // group_n
        pn = first_n + within % group_n

    MM: gl.constexpr = AMDMFMALayout(
        version=4,
        instr_shape=[INSTR, INSTR, 128 if INSTR == 16 else 64],
        transposed=True,
        warps_per_cta=[WARPS // 2, 2],
    )
    AL: gl.constexpr = DotOperandLayout(0, MM, 16)
    BL: gl.constexpr = DotOperandLayout(1, MM, 16)
    ASL: gl.constexpr = get_mfma_scale_layout(AL, [BM, BK // 32])
    BSL: gl.constexpr = get_mfma_scale_layout(BL, [BN, BK // 32])
    SHARED_A: gl.constexpr = compute_efficient_padded_shared_layout(
        AL, [BM, BK], gl.float8e4nv
    )
    LOAD: gl.constexpr = _copy_layout(SHARED_A, [BM, BK], WARPS)
    rm = gl.arange(0, BM, layout=SliceLayout(1, LOAD))
    LOAD_W: gl.constexpr = BlockedLayout([1, 16], [8, 8], [WARPS, 1], [1, 0])
    rn = gl.arange(0, BN, layout=SliceLayout(1, LOAD_W))
    rk = gl.arange(0, BK, layout=SliceLayout(0, LOAD))
    wk = gl.arange(0, BK, layout=SliceLayout(0, LOAD_W))
    am = gl.arange(0, BM, layout=SliceLayout(1, ASL))
    ak = gl.arange(0, BK // 32, layout=SliceLayout(0, ASL))
    bn = gl.arange(0, BN, layout=SliceLayout(1, BSL))
    bk = gl.arange(0, BK // 32, layout=SliceLayout(0, BSL))
    X += pm * BM * K
    W += pn * BN * K
    XS += pm * BM * (K // 32)
    WS += pn * (BN // 32) * (K // 32)
    rows_left = M - pm * BM
    xp = rm[:, None] * K + rk[None, :]
    wp = rn[:, None] * K + wk[None, :]
    xsp = (
        (am[:, None] // 32) * K
        + (ak[None, :] // 2) * 64
        + (ak[None, :] % 2) * 32
        + am[:, None] % 32
    )
    SHARED_W: gl.constexpr = SwizzledSharedLayout(16, 2, 8, [1, 0])
    bw_buf = gl.allocate_shared_memory(gl.float8e4nv, [1, BN, BK], SHARED_W)
    ax_buf = gl.allocate_shared_memory(gl.float8e4nv, [1, BM, BK], SHARED_A)
    async_copy.buffer_load_to_shared(ax_buf.index(0), X, xp, rm[:, None] < rows_left)
    async_copy.commit_group()
    async_copy.buffer_load_to_shared(bw_buf.index(0), W, wp)
    async_copy.commit_group()
    sa = buffer_load(XS, xsp, am[:, None] < rows_left, 0)
    pb = buffer_load(WS.to(gl.pointer_type(gl.uint32)), (bn // 32) * (K // 128) + 0)
    sb = ((pb[:, None] >> (bk[None, :] * 8)) & 255).to(gl.uint8)
    acc = gl.full((BM, BN), 0, gl.float32, MM)
    for kk in range(K // BK - 1):
        async_copy.wait_group(0)
        gl.barrier()
        aa = async_copy.load_shared_relaxed(ax_buf.index(0), AL)
        b = async_copy.load_shared_relaxed(bw_buf.index(0).permute((1, 0)), BL)
        gl.barrier()
        async_copy.buffer_load_to_shared(
            ax_buf.index(0), X, xp + (kk + 1) * BK, rm[:, None] < rows_left
        )
        async_copy.commit_group()
        async_copy.buffer_load_to_shared(bw_buf.index(0), W, wp + (kk + 1) * BK)
        async_copy.commit_group()
        nsa = buffer_load(XS, xsp + (kk + 1) * BK, am[:, None] < rows_left, 0)
        npb = buffer_load(
            WS.to(gl.pointer_type(gl.uint32)), (bn // 32) * (K // 128) + (kk + 1)
        )
        nsb = ((npb[:, None] >> (bk[None, :] * 8)) & 255).to(gl.uint8)
        acc = mfma_scaled(aa, sa, "e4m3", b, sb, "e4m3", acc)
        sa, sb = nsa, nsb
    async_copy.wait_group(0)
    gl.barrier()
    aa = async_copy.load_shared_relaxed(ax_buf.index(0), AL)
    b = async_copy.load_shared_relaxed(bw_buf.index(0).permute((1, 0)), BL)
    acc = mfma_scaled(aa, sa, "e4m3", b, sb, "e4m3", acc)
    STORE: gl.constexpr = BlockedLayout([1, 8], [4, 16], [WARPS, 1], [1, 0])
    out = gl.convert_layout(acc.to(gl.bfloat16), STORE)
    om = gl.arange(0, BM, layout=SliceLayout(1, STORE))
    on = gl.arange(0, BN, layout=SliceLayout(0, STORE))
    buffer_store(
        out,
        OUT + pm * BM * stride_om + pn * BN,
        om[:, None] * stride_om + on[None, :],
        om[:, None] < rows_left,
    )


def launch_mixed(
    x: torch.Tensor,
    x_scale: torch.Tensor,
    weight: torch.Tensor,
    weight_scale: torch.Tensor,
    out: torch.Tensor,
    cfg: "_Config",
) -> None:
    M, K = x.shape
    N = weight.shape[0]
    grid = (triton.cdiv(N, cfg.block_n), triton.cdiv(M, cfg.block_m // 2))
    packed_weight = torch.empty_like(weight)
    packed_xscale = torch.empty(
        (triton.cdiv(M, 32) * K,), dtype=x_scale.dtype, device=x_scale.device
    )
    _pack_weight[(triton.cdiv(max(N * K, triton.cdiv(M, 32) * K), 8192),)](
        weight, packed_weight, x_scale, packed_xscale, M, N, K, BLOCK=8192, num_warps=4
    )
    _block32_mixed_kernel[grid](
        x,
        packed_xscale,
        packed_weight,
        weight_scale,
        out,
        M,
        N,
        K,
        out.stride(0),
        LOGICAL_BM=cfg.block_m,
        BN=cfg.block_n,
        BK=cfg.block_k,
        N_FIRST=cfg.n_first,
        WARPS=cfg.num_warps,
        INSTR=cfg.matrix_instr_nonkdim,
        num_warps=cfg.num_warps,
        num_stages=cfg.num_stages,
        matrix_instr_nonkdim=cfg.matrix_instr_nonkdim,
        waves_per_eu=cfg.waves_per_eu,
    )


def launch_output(
    x: torch.Tensor,
    x_scale: torch.Tensor,
    weight: torch.Tensor,
    weight_scale: torch.Tensor,
    out: torch.Tensor,
    cfg: "_Config",
) -> None:
    M, K = x.shape
    N = weight.shape[0]
    grid = (triton.cdiv(N, cfg.block_n), triton.cdiv(M, cfg.block_m))
    packed_output_scale = torch.empty(
        (triton.cdiv(M, 32) * K,), dtype=x_scale.dtype, device=x_scale.device
    )
    _pack_output_scale[(triton.cdiv(M, 32),)](
        x_scale, packed_output_scale, M, K, num_warps=4
    )
    _block32_output_kernel[grid](
        x,
        packed_output_scale,
        weight,
        weight_scale,
        out,
        M,
        N,
        K,
        out.stride(0),
        BM=cfg.block_m,
        BN=cfg.block_n,
        BK=cfg.block_k,
        N_FIRST=cfg.n_first,
        WARPS=cfg.num_warps,
        INSTR=cfg.matrix_instr_nonkdim,
        num_warps=cfg.num_warps,
        num_stages=cfg.num_stages,
        matrix_instr_nonkdim=cfg.matrix_instr_nonkdim,
        waves_per_eu=cfg.waves_per_eu,
    )
