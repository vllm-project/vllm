class VibeVoiceAsrAudioInputs(TensorSchema):
    """Dimensions:
    - na: Number of audios
    - ns: Number of samples, a multiple of the tokenizer hop length
    """

    type: Literal["audio_values"] = "audio_values"
    input_values: Annotated[
        torch.Tensor | list[torch.Tensor],
        TensorShape("na", 1, "ns", dynamic_dims={"ns"}),
    ]


def parse_transcript_segments(text: str) -> list[dict[str, Any]]:
    """Parse the JSON list of segments generated by VibeVoice-ASR.

    Segments are decoded one at a time so that the complete segments of a
    truncated generation are kept. Parsing stops at the first segment that is
    malformed or lacks numeric timestamps.
    """
    text = text.strip().removeprefix("assistant").lstrip()
    if not text.startswith("["):
        return []

    decoder = json.JSONDecoder()
    segments: list[dict[str, Any]] = []
    pos = 1
    while True:
        while pos < len(text) and text[pos] in " \t\r\n,":
            pos += 1
        if pos >= len(text) or text[pos] == "]":
            return segments
        try:
            segment, pos = decoder.raw_decode(text, pos)
        except json.JSONDecodeError:
            return segments
        if not (
            isinstance(segment, dict)
            and isinstance(segment.get("Content"), str)
            and all(
                isinstance(segment.get(key), int | float) for key in ("Start", "End")
            )
        ):
            return segments
        segments.append(segment)


class VibeVoiceAsrMultiModalProjector(nn.Module):
    def __init__(self, config: VibeVoiceAsrConfig):
        super().__init__()
        acoustic_size = config.acoustic_tokenizer_encoder_config.hidden_size
        semantic_size = config.semantic_tokenizer_encoder_config.hidden_size
        hidden_size = config.text_config.hidden_size

        self.acoustic_linear_1 = nn.Linear(acoustic_size, hidden_size)
        self.acoustic_norm = RMSNorm(hidden_size, eps=1e-6)
        self.acoustic_linear_2 = nn.Linear(hidden_size, hidden_size)

        self.semantic_linear_1 = nn.Linear(semantic_size, hidden_size)
        self.semantic_norm = RMSNorm(hidden_size, eps=1e-6)
        self.semantic_linear_2 = nn.Linear(hidden_size, hidden_size)

    def forward(
        self, acoustic_latents: torch.Tensor, semantic_latents: torch.Tensor
    ) -> torch.Tensor:
        acoustic = self.acoustic_linear_2(
            self.acoustic_norm(self.acoustic_linear_1(acoustic_latents))
        )
        semantic = self.semantic_linear_2(
            self.semantic_norm(self.semantic_linear_1(semantic_latents))
        )
        return acoustic + semantic


class VibeVoiceAsrProcessingInfo(BaseProcessingInfo):
    def get_hf_config(self) -> VibeVoiceAsrConfig:
        return self.ctx.get_hf_config(VibeVoiceAsrConfig)

    def get_hf_processor(self, **kwargs: object) -> VibeVoiceAsrProcessor:
        return self.ctx.get_hf_processor(VibeVoiceAsrProcessor, **kwargs)

    def get_feature_extractor(
        self, **kwargs: object
    ) -> VibeVoiceAcousticTokenizerFeatureExtractor:
        return self.get_hf_processor(**kwargs).feature_extractor

    def get_hop_length(self) -> int:
        return self.get_hf_config().acoustic_tokenizer_encoder_config.hop_length

    def get_data_parser(self) -> MultiModalDataParser:
        return MultiModalDataParser(
            target_sr=self.get_feature_extractor().sampling_rate,
            target_channels=1,
        )

    def get_supported_mm_limits(self) -> Mapping[str, int | None]:
        return {"audio": None}

    def get_mm_max_tokens_per_item(
        self,
        seq_len: int,
        mm_counts: Mapping[str, int] | None = None,
    ) -> Mapping[str, int]:
        if (mm_counts or {}).get("audio", 0) <= 0:
            return {}

        sampling_rate = self.get_feature_extractor().sampling_rate
        max_tokens = math.ceil(
            MAX_AUDIO_DURATION_S * sampling_rate / self.get_hop_length()
        )
        return {"audio": min(seq_len, max_tokens)}


class VibeVoiceAsrDummyInputsBuilder(
    BaseDummyInputsBuilder[VibeVoiceAsrProcessingInfo]
):
    def get_dummy_text(self, mm_counts: Mapping[str, int]) -> str:
        return AUDIO_PLACEHOLDER * mm_counts.get("audio", 0)

    def get_dummy_mm_data(
        self,
        seq_len: int,
        mm_counts: Mapping[str, int],
        mm_options: MultiModalDummyOptions,
    ) -> MultiModalDataDict:
        max_tokens = self.info.get_mm_max_tokens_per_item(seq_len, mm_counts)
        if not max_tokens:
            return {}

        return {
            "audio": self._get_dummy_audios(
                length=max_tokens["audio"] * self.info.get_hop_length(),
                num_audios=mm_counts["audio"],
                overrides=mm_options.get("audio"),
            )
        }


class VibeVoiceAsrMultiModalProcessor(
    BaseMultiModalProcessor[VibeVoiceAsrProcessingInfo]
):
    def _get_hf_mm_text(self, mm_counts: Mapping[str, int]) -> str:
        return self.dummy_inputs.get_dummy_text(mm_counts)

    def _get_hf_mm_inputs(
        self,
        mm_items: MultiModalDataItems,
        hf_kwargs: Mapping[str, object],
    ) -> HFMultiModalInputs:
        hf_inputs = super()._get_hf_mm_inputs(mm_items, hf_kwargs)

        feature_extractor = self.info.get_feature_extractor(**hf_kwargs)
        return hf_inputs._replace(
            hf_kwargs=dict(
                hf_inputs.hf_kwargs,
                sampling_rate=feature_extractor.sampling_rate,
            )
        )

    def _postprocess_hf_mm_data(
        self,
        mm_inputs: Mapping[str, object],
        hf_processor_mm_kwargs: Mapping[str, object],
        processed_data: BatchFeature,
    ) -> BatchFeature:
        # The HF processor pads all audios to the longest one. Trim each audio
        # to its own hop-aligned length so that it is cached independently.
        padding_mask = processed_data.pop("padding_mask", None)
        if padding_mask is None:
            return processed_data

        hop_length = self.info.get_hop_length()
        num_samples = (padding_mask.sum(-1) + hop_length - 1) // hop_length
        processed_data["input_values"] = [
            values[:, : num_tokens * hop_length]
            for values, num_tokens in zip(
                processed_data["input_values"], num_samples.tolist()
            )
        ]
        return processed_data

    def _get_mm_fields_config(
        self,
        hf_inputs: BatchFeature,
        hf_processor_mm_kwargs: Mapping[str, object],
    ) -> Mapping[str, MultiModalFieldConfig]:
        return dict(input_values=MultiModalFieldConfig.batched("audio"))

    def _get_prompt_updates(
        self,
        mm_items: MultiModalDataItems,
        hf_processor_mm_kwargs: Mapping[str, object],
        out_mm_kwargs: MultiModalKwargsItems,
    ) -> Sequence[PromptUpdate]:
        processor = self.info.get_hf_processor(**hf_processor_mm_kwargs)
        audio_token_id = processor.audio_token_id
        hop_length = self.info.get_hop_length()

        def get_replacement(item_idx: int) -> list[int]:
            audios = mm_items.get_items("audio", AudioProcessorItems)
            num_tokens = math.ceil(audios.get_audio_length(item_idx) / hop_length)
            if num_tokens == 0:
                raise ValueError("The audio is too short to be transcribed.")
            return [audio_token_id] * num_tokens

        return [
            PromptReplacement(
                modality="audio",
                target=[audio_token_id],
                replacement=get_replacement,
            )
        ]


@MULTIMODAL_REGISTRY.register_processor(
    VibeVoiceAsrMultiModalProcessor,
    info=VibeVoiceAsrProcessingInfo,
    dummy_inputs=VibeVoiceAsrDummyInputsBuilder,
)
class VibeVoiceAsrForConditionalGeneration(
    nn.Module, SupportsMultiModal, SupportsPP, SupportsTranscription
):
    supports_diarized_transcription = True
    supported_languages = {
        code: LANGUAGES[code].title() for code in SUPPORTED_LANGUAGE_CODES
    }

    @classmethod
    def get_placeholder_str(cls, modality: str, i: int) -> str | None:
        if modality.startswith("audio"):
            return AUDIO_PLACEHOLDER

        raise ValueError("Only audio modality is supported")

    def __init__(self, *, vllm_config: VllmConfig, prefix: str = ""):
        super().__init__()
        config: VibeVoiceAsrConfig = vllm_config.model_config.hf_config
        self.config = config

        with self._mark_tower_model(vllm_config, "audio"):
            self.acoustic_tokenizer_encoder = VibeVoiceAcousticTokenizerEncoderModel(
                config.acoustic_tokenizer_encoder_config
            )
            self.semantic_tokenizer_encoder = VibeVoiceAcousticTokenizerEncoderModel(
                config.semantic_tokenizer_encoder_config
            )
            self.multi_modal_projector = VibeVoiceAsrMultiModalProjector(config)

        with self._mark_language_model(vllm_config):
            self.language_model = init_vllm_registered_model(
                vllm_config=vllm_config,
                hf_config=config.text_config,
                prefix=maybe_prefix(prefix, "language_model"),
                architectures=["Qwen2ForCausalLM"],
            )

        self.make_empty_intermediate_tensors = (
            self.language_model.make_empty_intermediate_tensors
        )

    def _parse_and_validate_audio_input(
        self, **kwargs: object
    ) -> VibeVoiceAsrAudioInputs | None:
        input_values = kwargs.pop("input_values", None)
        if input_values is None:
            return None

        return VibeVoiceAsrAudioInputs(input_values=input_values)

    def _encode_audio(self, input_values: torch.Tensor) -> torch.Tensor:
        """Encode a single waveform of shape `(1, 1, num_samples)`.

        Like HF, the waveform is encoded in chunks with the causal convolution
        state carried across chunk boundaries, which bounds activation memory
        for long-form audio. Unlike HF, the acoustic latents are used without
        VAE sampling noise, which keeps the audio embeddings deterministic and
        safe to reuse across the encoder and prefix caches.
        """
        acoustic_cache = semantic_cache = None
        acoustic_latents: list[torch.Tensor] = []
        semantic_latents: list[torch.Tensor] = []
        for chunk in input_values.split(self.config.acoustic_tokenizer_chunk_size, -1):
            acoustic = self.acoustic_tokenizer_encoder(
                chunk, padding_cache=acoustic_cache, use_cache=True
            )
            semantic = self.semantic_tokenizer_encoder(
                chunk, padding_cache=semantic_cache, use_cache=True
            )
            acoustic_cache = acoustic.padding_cache
            semantic_cache = semantic.padding_cache
            acoustic_latents.append(acoustic.latents)
            semantic_latents.append(semantic.latents)

        return self.multi_modal_projector(
            torch.cat(acoustic_latents, dim=1), torch.cat(semantic_latents, dim=1)
        ).squeeze(0)

    def embed_multimodal(self, **kwargs: object) -> MultiModalEmbeddings:
        audio_input = self._parse_and_validate_audio_input(**kwargs)
        if audio_input is None:
            return []

        dtype = self.multi_modal_projector.acoustic_linear_1.weight.dtype
        return tuple(
            self._encode_audio(values.to(dtype).view(1, 1, -1))
            for values in audio_input["input_values"]
        )

    def forward(
        self,
        input_ids: torch.Tensor | None,
        positions: torch.Tensor,
        intermediate_tensors: IntermediateTensors | None = None,
        inputs_embeds: torch.Tensor | None = None,
        **kwargs: object,
    ) -> torch.Tensor | IntermediateTensors:
        if intermediate_tensors is not None:
            inputs_embeds = None

        return self.language_model.model(
            input_ids, positions, intermediate_tensors, inputs_embeds=inputs_embeds
        )

    def compute_logits(self, hidden_states: torch.Tensor) -> torch.Tensor | None:
        return self.language_model.compute_logits(hidden_states)

    def load_weights(self, weights: Iterable[tuple[str, torch.Tensor]]) -> set[str]:
        loader = AutoWeightsLoader(self)
        return loader.load_weights(weights)

    # === Transcription API === #

    @classmethod
    def get_speech_to_text_config(
        cls, model_config: ModelConfig, task_type: str
    ) -> SpeechToTextConfig:
        processor = cached_processor_from_config(model_config)
        # Long-form audio is transcribed in a single pass, so server-side
        # chunking is disabled to keep speaker IDs and timestamps consistent.
        return SpeechToTextConfig(
            sample_rate=processor.feature_extractor.sampling_rate,
            max_audio_clip_s=None,
            min_energy_split_window_size=None,
        )

    @classmethod
    def get_num_audio_tokens(
        cls,
        audio_duration_s: float,
        stt_config: SpeechToTextConfig,
        model_config: ModelConfig,
    ) -> int | None:
        hop_length = model_config.hf_config.acoustic_tokenizer_encoder_config.hop_length
        return math.ceil(audio_duration_s * stt_config.sample_rate / hop_length)

    @classmethod
    def get_generation_prompt(cls, stt_params: SpeechToTextParams) -> PromptType:
        if stt_params.task_type != "transcribe":
            raise ValueError("VibeVoice-ASR does not support translation.")

        stt_config = stt_params.stt_config
        duration_s = len(stt_params.audio) / stt_config.sample_rate
        context = "\n".join(
            text.strip()
            for text in (stt_params.request_prompt, stt_params.hotwords)
            if text and text.strip()
        )
        if context:
            instruction = (
                f"This is a {duration_s:.2f} seconds audio, with extra info: "
                f"{context}\n\nPlease transcribe it with these keys: "
                f"{TRANSCRIPTION_KEYS}"
            )
        else:
            instruction = (
                f"This is a {duration_s:.2f} seconds audio, please transcribe "
                f"it with these keys: {TRANSCRIPTION_KEYS}"
            )

        # The HF chat template has no generation prompt; the model emits the
        # assistant header itself, so it is added here to skip those tokens.
        prompt = (
            f"<|im_start|>system\n{SYSTEM_PROMPT}<|im_end|>\n"
            f"<|im_start|>user\n{AUDIO_PLACEHOLDER}\n{instruction}<|im_end|>\n"
            "<|im_start|>assistant\n"
        )
        return TextPrompt(
            prompt=prompt,
            multi_modal_data={"audio": (stt_params.audio, stt_config.sample_rate)},
        )

    @classmethod
    def post_process_output(cls, text: str) -> str:
        segments = parse_transcript_segments(text)
        if not segments:
            return text.strip()
        return " ".join(segment["Content"].strip() for segment in segments).strip()

    @classmethod
    def parse_diarized_transcript(cls, text: str) -> list[DiarizedTranscriptionSegment]:
        return [
            DiarizedTranscriptionSegment(
                start=float(segment["Start"]),
                end=float(segment["End"]),
                speaker=str(segment.get("Speaker", 0)),
                text=segment["Content"].strip(),
            )
            for segment in parse_transcript_segments(text)
            if segment["Content"].strip()
        ]
