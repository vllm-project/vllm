"""Compile the `vllm.Render` protos into Python modules.

The protos are the ones the Rust frontend serves, in `rust/proto/`, so the
Python render server and `vllm-rs render` share one wire contract. The
generated `*_pb2*.py` files are written next to this script and are not
checked in. `setup.py` runs this during the package build; run it by hand
after editing a proto:

    python -m vllm.entrypoints.scale_out.render.grpc.compile_protos

Requires `grpcio-tools`.
"""

from __future__ import annotations

import sys
from pathlib import Path

PACKAGE = "vllm.entrypoints.scale_out.render.grpc"
PROTO_NAMES: tuple[str, ...] = ("inference", "render")

_HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# SPDX-FileCopyrightText: Copyright contributors to the vLLM project\n"
    "# mypy: ignore-errors\n"
    "# Generated by compile_protos.py from rust/proto. Do not edit.\n"
)

OUT_DIR = Path(__file__).resolve().parent
PROTO_DIR = OUT_DIR.parents[4] / "rust" / "proto"


def _patch_generated(path: Path) -> None:
    """Make the sibling imports protoc emits (`import render_pb2`) absolute."""
    lines = path.read_text().splitlines(keepends=True)
    for i, line in enumerate(lines):
        for name in PROTO_NAMES:
            if line.startswith(f"import {name}_pb2 as "):
                lines[i] = f"from {PACKAGE} {line}"
    text = "".join(lines)
    if not text.startswith("# SPDX-License-Identifier"):
        text = _HEADER + text
    path.write_text(text)


def compile_protos(proto_dir: Path = PROTO_DIR, out_dir: Path = OUT_DIR) -> int:
    try:
        import grpc_tools
        from grpc_tools import protoc
    except ImportError:
        print(
            "grpcio-tools is not installed: pip install grpcio-tools", file=sys.stderr
        )
        return 1

    proto_files = [proto_dir / f"{name}.proto" for name in PROTO_NAMES]
    missing = [str(p) for p in proto_files if not p.exists()]
    if missing:
        print(f"Proto files not found: {', '.join(missing)}", file=sys.stderr)
        return 1

    well_known_dir = Path(grpc_tools.__file__).parent / "_proto"
    rc = protoc.main(
        [
            "grpc_tools.protoc",
            f"--proto_path={proto_dir}",
            f"--proto_path={well_known_dir}",
            f"--python_out={out_dir}",
            f"--pyi_out={out_dir}",
            f"--grpc_python_out={out_dir}",
            *map(str, proto_files),
        ]
    )
    if rc != 0:
        print(f"protoc returned {rc}", file=sys.stderr)
        return rc

    for generated in sorted(out_dir.glob("*_pb2*.py*")):
        _patch_generated(generated)
    return 0


if __name__ == "__main__":
    sys.exit(compile_protos())
