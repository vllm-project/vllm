def parse_table(text: str, k: int, world_size: int) -> dict[int, list[list[int]]]:
    """Returns `{layer: [rank r's first k experts, ...]}` for layers 1-60.

    Raises:
        ValueError: a layer or rank is missing, or a row has fewer than `k`
            distinct experts of its rank.

    """
    local = NUM_EXPERTS // world_size
    rows: dict[tuple[int, int], list[int]] = {}
    for line in text.splitlines():
        parts = line.split()
        if not parts or not parts[0].isdigit():
            continue
        layer, rank = int(parts[0]), int(parts[1])
        ids = [int(p.split("(")[0]) for p in parts[2:]][:k]
        if len(set(ids)) != k or any(e // local != rank for e in ids):
            raise ValueError(
                f"EP buddy table: layer {layer} rank {rank} needs {k} distinct "
                f"experts of the rank (ids {rank * local}-{rank * local + local - 1})"
            )
        rows[layer, rank] = ids
    table = {}
    for layer in range(FIRST_LAYER, LAST_LAYER + 1):
        missing = [r for r in range(world_size) if (layer, r) not in rows]
        if missing:
            raise ValueError(f"EP buddy table: layer {layer} lacks ranks {missing}")
        table[layer] = [rows[layer, r] for r in range(world_size)]
    return table


def load_table(path: str, k: int, world_size: int) -> dict[int, list[list[int]]]:
    """`parse_table` of the file at `path`, or of `DEFAULT_TABLE` when empty."""
    text = Path(path).read_text() if path else DEFAULT_TABLE
    return parse_table(text, k, world_size)
