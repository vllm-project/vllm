/// One scheduler step's KV cache events (`KVEventBatch`).
#[derive(Debug, Clone, PartialEq, Serialize_tuple, Deserialize_tuple)]
pub struct KvEventBatch {
    /// Engine wall-clock time, in seconds since the Unix epoch.
    pub ts: f64,
    pub events: Vec<KvCacheEvent>,
    #[serde(default)]
    pub data_parallel_rank: Option<u32>,
}

impl KvEventBatch {
    /// Decode a published payload, skipping fields appended by newer engines.
    pub fn decode(payload: &[u8]) -> Result<Self> {
        AllowTrailingFields::deserialize_as(&mut rmp_serde::Deserializer::new(payload)).map_err(
            |error: rmp_serde::decode::Error| Error::Decode {
                target_type: "KvEventBatch",
                message: error.to_report_string(),
            },
        )
    }
}

/// A KV cache event, tagged with its Python class name.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum KvCacheEvent {
    BlockStored(BlockStored),
    BlockRemoved(BlockRemoved),
    AllBlocksCleared,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct BlockStored {
    pub block_hashes: Vec<ExternalBlockHash>,
    pub parent_block_hash: Option<ExternalBlockHash>,
    pub token_ids: Vec<u32>,
    pub block_size: u32,
    /// Deprecated in favor of `lora_name`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lora_id: Option<i64>,
    pub medium: Option<String>,
    pub lora_name: Option<String>,
    /// Extra keys used in block hash computation, one entry per block in
    /// block_hashes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub extra_keys: Option<Vec<Option<Vec<ExtraKeyValue>>>>,
    /// Store events carry cache-spec metadata so consumers can classify and
    /// filter groups as they are learned. Remove events only need group_idx+hash.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub group_idx: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub kv_cache_spec_kind: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub kv_cache_spec_sliding_window: Option<u32>,
    /// LOCAL or REMOTE relative to the publisher; None means unspecified.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub locality: Option<String>,
    /// Secondary offloading tier identifier, if generated by one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ownership: Option<String>,
    /// Session that triggered this store or reuse report.
    ///
    /// This identifies the request context that emitted the event, not exclusive
    /// ownership of the underlying block, which may be shared across sessions.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session_id: Option<String>,
    /// Tokens beyond each block used in its hash, one list per block_hashes entry.
    /// None when lookahead hashing is disabled.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lookahead_token_ids: Option<Vec<Vec<u32>>>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct BlockRemoved {
    pub block_hashes: Vec<ExternalBlockHash>,
    pub medium: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub group_idx: Option<u32>,
    /// LOCAL or REMOTE relative to the publisher; None means unspecified.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub locality: Option<String>,
    /// Secondary offloading tier identifier, if generated by one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ownership: Option<String>,
}

/// A published block hash (`ExternalBlockHash`), in the form it was published:
/// the low 64 bits of the digest under `VLLM_KV_EVENTS_USE_INT_BLOCK_HASHES`
/// (the default), the digest otherwise. A connector that forwards its own
/// hashes may publish signed integers.
#[derive(Clone, PartialEq, Eq)]
pub enum ExternalBlockHash {
    Unsigned(u64),
    Signed(i64),
    Digest(Vec<u8>),
}

impl fmt::Debug for ExternalBlockHash {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Unsigned(value) => write!(formatter, "Unsigned({value:#018x})"),
            Self::Signed(value) => write!(formatter, "Signed({value})"),
            Self::Digest(digest) => write!(formatter, "Digest({})", hex::encode(digest)),
        }
    }
}

impl Default for ExternalBlockHash {
    fn default() -> Self {
        Self::Unsigned(0)
    }
}

impl Serialize for ExternalBlockHash {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        match self {
            Self::Unsigned(value) => serializer.serialize_u64(*value),
            Self::Signed(value) => serializer.serialize_i64(*value),
            Self::Digest(digest) => serializer.serialize_bytes(digest),
        }
    }
}

impl<'de> Deserialize<'de> for ExternalBlockHash {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        struct HashVisitor;

        impl Visitor<'_> for HashVisitor {
            type Value = ExternalBlockHash;

            fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str("a block hash as bytes or a 64-bit integer")
            }

            fn visit_bytes<E>(self, value: &[u8]) -> std::result::Result<Self::Value, E> {
                Ok(ExternalBlockHash::Digest(value.to_vec()))
            }

            fn visit_byte_buf<E>(self, value: Vec<u8>) -> std::result::Result<Self::Value, E> {
                Ok(ExternalBlockHash::Digest(value))
            }

            fn visit_u64<E>(self, value: u64) -> std::result::Result<Self::Value, E> {
                Ok(ExternalBlockHash::Unsigned(value))
            }

            fn visit_i64<E>(self, value: i64) -> std::result::Result<Self::Value, E> {
                Ok(match u64::try_from(value) {
                    Ok(value) => ExternalBlockHash::Unsigned(value),
                    Err(_) => ExternalBlockHash::Signed(value),
                })
            }
        }

        deserializer.deserialize_any(HashVisitor)
    }
}

/// One untagged input to a block's hash other than its tokens, as Python's
/// `to_event_extra_keys` publishes it: a LoRA name or cache salt (text), a
/// prompt embedding digest (data), or an `(mm_identifier, offset)` tuple.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ExtraKeyValue {
    Text(String),
    Data(Vec<u8>),
    Integer(i64),
    Tuple(Vec<ExtraKeyValue>),
}

impl Serialize for ExtraKeyValue {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        match self {
            Self::Text(text) => serializer.serialize_str(text),
            Self::Data(data) => serializer.serialize_bytes(data),
            Self::Integer(value) => serializer.serialize_i64(*value),
            Self::Tuple(items) => items.serialize(serializer),
        }
    }
}

impl<'de> Deserialize<'de> for ExtraKeyValue {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        struct KeyVisitor;

        impl<'de> Visitor<'de> for KeyVisitor {
            type Value = ExtraKeyValue;

            fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str("a string, bytes, an integer, or a sequence of them")
            }

            fn visit_str<E>(self, value: &str) -> std::result::Result<Self::Value, E> {
                Ok(ExtraKeyValue::Text(value.to_string()))
            }

            fn visit_bytes<E>(self, value: &[u8]) -> std::result::Result<Self::Value, E> {
                Ok(ExtraKeyValue::Data(value.to_vec()))
            }

            fn visit_i64<E>(self, value: i64) -> std::result::Result<Self::Value, E> {
                Ok(ExtraKeyValue::Integer(value))
            }

            fn visit_u64<E: serde::de::Error>(
                self,
                value: u64,
            ) -> std::result::Result<Self::Value, E> {
                i64::try_from(value)
                    .map(ExtraKeyValue::Integer)
                    .map_err(|_| E::custom("extra key integer out of range"))
            }

            fn visit_seq<A: SeqAccess<'de>>(
                self,
                mut seq: A,
            ) -> std::result::Result<Self::Value, A::Error> {
                let mut items = Vec::new();
                while let Some(item) = seq.next_element()? {
                    items.push(item);
                }
                Ok(ExtraKeyValue::Tuple(items))
            }
        }

        deserializer.deserialize_any(KeyVisitor)
    }
}

