//! KV cache events published by the engine's `ZmqEventPublisher`.
//!
//! Original Python definitions:
//! <https://github.com/vllm-project/vllm/blob/main/vllm/distributed/kv_events.py>

use serde::{Deserialize, Serialize};
use serde_tuple::{Deserialize_tuple, Serialize_tuple};
use serde_with::{DeserializeAs as _, serde_as};
use thiserror_ext::AsReport as _;

use super::serde_utils::AllowTrailingFields;
use crate::error::{Error, Result};

/// One scheduler step's KV cache events (`KVEventBatch`).
#[derive(Debug, Clone, PartialEq, Serialize_tuple, Deserialize_tuple)]
pub struct KvEventBatch {
    /// Engine wall-clock time, in seconds since the Unix epoch.
    pub ts: f64,
    pub events: Vec<KvCacheEvent>,
    #[serde(default)]
    pub data_parallel_rank: Option<u32>,
}

impl KvEventBatch {
    /// Decode a published payload, skipping fields appended by newer engines.
    pub fn decode(payload: &[u8]) -> Result<Self> {
        AllowTrailingFields::deserialize_as(&mut rmp_serde::Deserializer::new(payload)).map_err(
            |error: rmp_serde::decode::Error| Error::Decode {
                target_type: "KvEventBatch",
                message: error.to_report_string(),
            },
        )
    }
}

/// A KV cache event, tagged with its Python class name.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum KvCacheEvent {
    BlockStored(BlockStored),
    BlockRemoved(BlockRemoved),
    AllBlocksCleared,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct BlockStored {
    pub block_hashes: Vec<ExternalBlockHash>,
    pub parent_block_hash: Option<ExternalBlockHash>,
    pub token_ids: Vec<u32>,
    pub block_size: u32,
    /// Deprecated in favor of `lora_name`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lora_id: Option<i64>,
    pub medium: Option<String>,
    pub lora_name: Option<String>,
    /// Extra keys used in block hash computation, one entry per block in
    /// block_hashes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub extra_keys: Option<Vec<Option<Vec<ExtraKeyValue>>>>,
    /// Store events carry cache-spec metadata so consumers can classify and
    /// filter groups as they are learned. Remove events only need group_idx+hash.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub group_idx: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub kv_cache_spec_kind: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub kv_cache_spec_sliding_window: Option<u32>,
    /// LOCAL or REMOTE relative to the publisher; None means unspecified.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub locality: Option<String>,
    /// Secondary offloading tier identifier, if generated by one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ownership: Option<String>,
    /// Session that triggered this store or reuse report.
    ///
    /// This identifies the request context that emitted the event, not exclusive
    /// ownership of the underlying block, which may be shared across sessions.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session_id: Option<String>,
    /// Tokens beyond each block used in its hash, one list per block_hashes entry.
    /// None when lookahead hashing is disabled.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lookahead_token_ids: Option<Vec<Vec<u32>>>,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct BlockRemoved {
    pub block_hashes: Vec<ExternalBlockHash>,
    pub medium: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub group_idx: Option<u32>,
    /// LOCAL or REMOTE relative to the publisher; None means unspecified.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub locality: Option<String>,
    /// Secondary offloading tier identifier, if generated by one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ownership: Option<String>,
}

/// A published block hash (`ExternalBlockHash`), in the form it was published:
/// the low 64 bits of the digest under `VLLM_KV_EVENTS_USE_INT_BLOCK_HASHES`
/// (the default), the digest otherwise. A connector that forwards its own
/// hashes may publish signed integers.
#[serde_as]
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum ExternalBlockHash {
    Unsigned(u64),
    Signed(i64),
    Digest(#[serde_as(as = "serde_with::Bytes")] Vec<u8>),
}

/// One untagged input to a block's hash other than its tokens, as Python's
/// `to_event_extra_keys` publishes it: a LoRA name or cache salt (text), a
/// prompt embedding digest (data), or an `(mm_identifier, offset)` tuple.
// Decoded from the MessagePack value: `untagged` would read a digest that is
// valid UTF-8 as text.
#[serde_as]
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(untagged, try_from = "rmpv::Value")]
pub enum ExtraKeyValue {
    Text(String),
    Data(#[serde_as(as = "serde_with::Bytes")] Vec<u8>),
    Integer(i64),
    Tuple(Vec<ExtraKeyValue>),
}

impl TryFrom<rmpv::Value> for ExtraKeyValue {
    type Error = &'static str;

    fn try_from(value: rmpv::Value) -> std::result::Result<Self, Self::Error> {
        use rmpv::Value;

        match value {
            Value::String(text) => text.into_str().map(Self::Text),
            Value::Binary(data) => Some(Self::Data(data)),
            Value::Integer(integer) => integer.as_i64().map(Self::Integer),
            Value::Array(items) => {
                let items = items.into_iter().map(Self::try_from);
                Some(Self::Tuple(items.collect::<std::result::Result<_, _>>()?))
            }
            _ => None,
        }
        .ok_or("expected text, bytes, a 64-bit integer, or a sequence of them")
    }
}

#[cfg(test)]
mod tests {
    use super::ExternalBlockHash::{Digest, Signed, Unsigned};
    use super::ExtraKeyValue::{Data, Integer, Text, Tuple};
    use super::*;

    #[test]
    fn decodes_a_batch_as_the_engine_encodes_it() {
        // msgspec.msgpack.encode(KVEventBatch(1.5, [BlockStored([2**64 - 1, -7, b"\xab\xcd"], None,
        // [1, 70000], 1, None, "GPU", None, [("salt", b"digest", ("img", 3)), None, None]),
        // BlockRemoved([7], "GPU"), AllBlocksCleared()], 0)).hex()
        let payload = "93cb3ff800000000000093de0009a474797065ab426c6f636b53746f726564ac626c6f636b5f\
            68617368657393cffffffffffffffffff9c402abcdb1706172656e745f626c6f636b5f68617368c0a9746f6\
            b656e5f6964739201ce00011170aa626c6f636b5f73697a6501a76c6f72615f6964c0a66d656469756da347\
            5055a96c6f72615f6e616d65c0aa65787472615f6b6579739393a473616c74c40664696765737492a3696d6\
            703c0c083a474797065ac426c6f636b52656d6f766564ac626c6f636b5f6861736865739107a66d65646975\
            6da347505581a474797065b0416c6c426c6f636b73436c656172656400";
        let image = Tuple(vec![Text("img".to_string()), Integer(3)]);
        let keys = vec![Text("salt".to_string()), Data(b"digest".to_vec()), image];
        let stored = BlockStored {
            block_hashes: vec![Unsigned(u64::MAX), Signed(-7), Digest(vec![0xab, 0xcd])],
            token_ids: vec![1, 70000],
            block_size: 1,
            medium: Some("GPU".to_string()),
            extra_keys: Some(vec![Some(keys), None, None]),
            ..Default::default()
        };
        let removed = BlockRemoved {
            block_hashes: vec![Unsigned(7)],
            medium: Some("GPU".to_string()),
            ..Default::default()
        };
        let events = vec![
            KvCacheEvent::BlockStored(stored),
            KvCacheEvent::BlockRemoved(removed),
            KvCacheEvent::AllBlocksCleared,
        ];
        let batch = KvEventBatch::decode(&hex::decode(payload).unwrap()).unwrap();
        assert_eq!(
            (batch.ts, batch.events, batch.data_parallel_rank),
            (1.5, events, Some(0))
        );
    }
}
