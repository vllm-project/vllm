    /// The type tag and field entries of an encoded event.
    fn encoded_fields(event: &KvCacheEvent) -> (String, Vec<(Value, Value)>) {
        let Value::Map(mut entries) =
            decode_value(&rmp_serde::to_vec_named(event).unwrap()).unwrap()
        else {
            panic!("events encode as maps");
        };
        let tag = entries.iter().position(|(key, _)| key.as_str() == Some("type")).unwrap();
        let (_, event_type) = entries.remove(tag);
        (event_type.as_str().unwrap().to_string(), entries)
    }

    /// Whether an event with these fields decodes.
    fn decodes(event_type: &str, fields: Vec<(Value, Value)>) -> bool {
        let mut entries = vec![(Value::from("type"), Value::from(event_type))];
        entries.extend(fields);
        let mut payload = Vec::new();
        rmpv::encode::write_value(&mut payload, &Value::Map(entries)).unwrap();
        rmp_serde::from_slice::<KvCacheEvent>(&payload).is_ok()
    }

    #[test]
    fn decoder_covers_every_event_type_and_field_of_the_python_engine() {
        let vectors = python_vectors();
        assert_eq!(vectors.batch_fields, ["ts", "events", "data_parallel_rank"]);

        let events = events_with_every_field();
        let decoded: BTreeSet<String> =
            events.iter().map(|event| encoded_fields(event).0).collect();
        let published: BTreeSet<String> = vectors.event_fields.keys().cloned().collect();
        assert_eq!(decoded, published);

        for event in &events {
            let (event_type, fields) = encoded_fields(event);
            let published = &vectors.event_fields[&event_type];

            let decoded: BTreeSet<&str> =
                fields.iter().map(|(field, _)| field.as_str().unwrap()).collect();
            let published_names: BTreeSet<&str> = published.keys().map(String::as_str).collect();
            assert_eq!(decoded, published_names, "fields of {event_type}");

            // The engine omits a field that is at its default.
            for field in decoded {
                let without = fields
                    .iter()
                    .filter(|(name, _)| name.as_str() != Some(field))
                    .cloned()
                    .collect();
                assert!(
                    published[field].required || decodes(&event_type, without),
                    "{event_type} must decode without the optional `{field}`"
                );
            }
        }
    }

