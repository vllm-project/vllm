"""Replay tools/formal/shm_broadcast/message_queue.qnt traces on MessageQueue.

Each trace was generated by `quint run --mbt` on the `skipIdleFenced`
configuration (the protocol this code implements). Every model action is
driven through the MessageQueue method that implements it, and after every
step the shared-memory state is compared with the model's: written and read
flags, parked flags, and each reader's pending notification. A change to
either side that the other does not mirror fails here.

Regenerate the traces with `tools/formal/shm_broadcast/gen_traces.sh` after
changing the model; the test also fails while the stored model hash is stale.
"""

import hashlib
import json
import threading
import time
from contextlib import AbstractContextManager
from pathlib import Path
from unittest import mock

import pytest

from vllm.distributed.device_communicators import shm_broadcast
from vllm.distributed.device_communicators.shm_broadcast import MessageQueue

FORMAL = Path(__file__).parents[2] / "tools" / "formal" / "shm_broadcast"
TRACE_FILE = FORMAL / "traces" / "skipIdleFenced.jsonl"
TRACES = (
    [json.loads(line) for line in TRACE_FILE.read_text().splitlines()]
    if TRACE_FILE.exists()
    else []
)
# Long enough for libzmq's I/O thread to move one notification; the model's
# `deliver` is that thread's step, which the test cannot drive directly.
DELIVER_TIMEOUT_MS = 5000
# A notification crosses libzmq's inproc/IPC pipe in microseconds.
CONFLATE_SETTLE_S = 0.05


def test_traces_match_the_model():
    """The traces were generated from the model as it is now."""
    model = (FORMAL / "message_queue.qnt").read_bytes()
    recorded = (FORMAL / "traces" / "message_queue.qnt.sha256").read_text().split()[0]
    assert TRACES, "no traces; run tools/formal/shm_broadcast/gen_traces.sh"
    assert hashlib.sha256(model).hexdigest() == recorded, (
        "message_queue.qnt changed; regenerate the traces with "
        "tools/formal/shm_broadcast/gen_traces.sh and update MessageQueue to match"
    )


class _Replay:
    """Drives a writer and two local readers through model actions."""

    def __init__(self, n_reader: int, max_chunks: int):
        self.writer = MessageQueue(
            n_reader=n_reader,
            n_local_reader=n_reader,
            max_chunk_bytes=1024,
            max_chunks=max_chunks,
        )
        handle = self.writer.export_handle()
        self.readers = [
            MessageQueue.create_from_handle(handle, rank=r) for r in range(n_reader)
        ]
        self.write_ctx: AbstractContextManager[memoryview] | None = None
        self.subscribed = False

    def close(self):
        if self.write_ctx is not None:
            self.write_ctx.__exit__(None, None, None)
        self.writer.shutdown()
        for reader in self.readers:
            reader.shutdown()

    # -- actions ----------------------------------------------------------

    def handshake(self):
        threads = [threading.Thread(target=r.wait_until_ready) for r in self.readers]
        for t in threads:
            t.start()
        self.writer.wait_until_ready()
        for t in threads:
            t.join(timeout=10)
        assert all(
            r._wake_mode == shm_broadcast._WAKE_PARKED_PING for r in self.readers
        )
        self.subscribed = True

    def writer_acquire(self):
        ctx = self.writer.acquire_write(timeout=5)
        buf = ctx.__enter__()
        self.write_ctx = ctx
        buf[0] = 0
        buf[1:3] = (1).to_bytes(2, "big")
        payload = b"\x80\x05N."  # pickle of None
        buf[3:7] = len(payload).to_bytes(4, "big")
        buf[7 : 7 + len(payload)] = payload

    def writer_flush(self):
        ctx, self.write_ctx = self.write_ctx, None
        assert ctx is not None, "writerFlush without writerAcquire"
        ctx.__exit__(None, None, None)

    def writer_notify(self, expect_ping: bool):
        cond = self.writer._spin_condition
        with mock.patch.object(cond, "notify", wraps=cond.notify) as notify:
            self.writer._notify_readers()
        assert notify.call_count == int(expect_ping)

    def reader_read(self, r: int):
        assert self.readers[r].dequeue(timeout=5) is None

    def reader_park(self, r: int):
        self.readers[r]._set_parked(True)

    def reader_recheck(self, r: int, want_poll: bool):
        assert self.readers[r]._recheck_parked() == want_poll
        if not want_poll:
            self.readers[r]._set_parked(False)

    def reader_poll(self, r: int):
        cond = self.readers[r]._spin_condition
        assert cond.local_notify_socket.poll(timeout=0), (
            "model woke a reader with no ping"
        )
        # The reader's real wait: returns at once, consuming every pending ping.
        cond.poll_notify(timeout_ms=DELIVER_TIMEOUT_MS)
        self.readers[r]._set_parked(False)

    def reader_drain(self, r: int):
        cond = self.readers[r]._spin_condition
        assert cond.local_notify_socket.poll(timeout=DELIVER_TIMEOUT_MS)
        cond.drain_notify()

    def reader_timeout(self, r: int):
        self.readers[r]._set_parked(False)

    def deliver(self, r: int, into_full_slot: bool):
        sock = self.readers[r]._spin_condition.local_notify_socket
        assert sock.poll(timeout=DELIVER_TIMEOUT_MS), "notification never arrived"
        if into_full_slot:
            # zmq exposes no count of pending messages, so poll() cannot see
            # a ping that joins one already pending. Give libzmq's I/O thread
            # time to move it; if it arrived late, the drain or poll that
            # follows would leave it behind and the next comparison fails.
            time.sleep(CONFLATE_SETTLE_S)

    # -- observation ------------------------------------------------------

    def flags(self) -> tuple[list[int], list[list[int]], list[int]]:
        buffer = self.writer.buffer
        written, read = [], []
        for s in range(buffer.max_chunks):
            with buffer.get_metadata(s) as meta:
                written.append(meta[0])
                read.append([meta[r + 1] for r in range(buffer.n_reader)])
        with buffer.get_park_flags() as park:
            parked = [park[r] for r in range(buffer.n_reader)]
        return written, read, parked


@pytest.mark.skipif(
    shm_broadcast._full_fence is None, reason="needs the spinloop extension"
)
@pytest.mark.parametrize(
    "states", TRACES, ids=[f"trace{i}" for i in range(len(TRACES))]
)
def test_code_follows_model_trace(states: list[dict]):
    replay = _Replay(len(states[0]["rPc"]), len(states[0]["written"]))
    try:
        for before, after in zip(states, states[1:]):
            action, r = after["a"], after["r"]
            if action == "writerHandshake":
                replay.handshake()
            elif action == "writerAcquire":
                replay.writer_acquire()
            elif action == "writerFlush":
                replay.writer_flush()
            elif action == "writerNotify":
                replay.writer_notify(after["sent"] != before["sent"])
            elif action == "readerRead":
                replay.reader_read(r)
            elif action == "readerPark":
                pass  # the store sits in the model's buffer until the flush
            elif action == "readerFlushPark":
                replay.reader_park(r)
            elif action == "readerRecheck":
                replay.reader_recheck(r, after["rPc"][r] == "park")
            elif action == "readerPoll":
                replay.reader_poll(r)
            elif action == "readerDrain":
                replay.reader_drain(r)
            elif action == "readerTimeout":
                replay.reader_timeout(r)
            elif action == "deliver":
                replay.deliver(r, before["conflated"][r])
            elif action in ("idle", "subArrive"):
                pass  # no code step: time passing, or a connect in progress
            else:
                pytest.fail(f"model action {action!r} has no code step")
            _assert_matches(replay, after, action)
    finally:
        replay.close()


def _assert_matches(replay: _Replay, model: dict, action: str):
    written, read, parked = replay.flags()
    readers = range(len(model["rPc"]))
    slots = range(len(model["written"]))
    for s in slots:
        # The replay publishes a write at the model's flush (writerFlush), so
        # both sides hold the same visible flags at every step.
        assert bool(written[s]) == model["written"][s], f"{action}: written[{s}]"
        want_read = [model["readFlag"][s][r] for r in readers]
        assert [bool(x) for x in read[s]] == want_read, f"{action}: readFlag[{s}]"
    for r in readers:
        # The code stores the flag at the model's flush (readerFlushPark);
        # a store still buffered in the model is not yet in the code either.
        assert bool(parked[r]) == model["parked"][r], f"{action}: parked[{r}]"
    if replay.subscribed:
        for r in readers:
            sock = replay.readers[r]._spin_condition.local_notify_socket
            in_flight = model["inflight"][r] > 0
            if model["conflated"][r] and not in_flight:
                assert sock.poll(timeout=DELIVER_TIMEOUT_MS), f"{action}: ping {r}"
            elif not model["conflated"][r] and not in_flight:
                time.sleep(0.001)
                assert not sock.poll(timeout=0), f"{action}: stray ping for {r}"
