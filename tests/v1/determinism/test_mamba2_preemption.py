"""Preserve a request's decode history across forced Mamba2 recomputation.

This tests preemption invariance, not equality between independently supplied
prompt tokens and tokens generated by decode. Prefix caching is disabled.
"""

import os
import struct

import pytest
import torch

from tests.utils import multi_gpu_marks
from vllm import SamplingParams
from vllm.inputs import TokensPrompt
from vllm.platforms import current_platform


def _signature(output):
    completion = output.outputs[0]
    assert completion.logprobs is not None
    return (
        list(completion.token_ids),
        [
            {token: struct.pack("<f", value.logprob) for token, value in row.items()}
            for row in completion.logprobs
        ],
    )


@pytest.mark.skipif(not current_platform.is_cuda(), reason="Requires CUDA")
@pytest.mark.timeout(600)
@pytest.mark.parametrize("enforce_eager", [True, False])
def test_mamba2_mixed_repeated_preemption(vllm_runner, monkeypatch, enforce_eager):
    monkeypatch.setenv("VLLM_BATCH_INVARIANT", "1")
    monkeypatch.setenv("VLLM_ENABLE_V1_MULTIPROCESSING", "0")
    monkeypatch.setenv("VLLM_USE_FLASHINFER_SAMPLER", "0")
    model = os.getenv("VLLM_TEST_MODEL", "ibm-granite/granite-4.0-h-350m")
    with vllm_runner(
        model,
        dtype="bfloat16",
        enforce_eager=enforce_eager,
        max_model_len=1024,
        max_num_seqs=8,
        max_num_batched_tokens=1024,
        enable_chunked_prefill=True,
        enable_prefix_caching=False,
        mamba_ssm_cache_dtype="auto",
        gpu_memory_utilization=0.25,
        tensor_parallel_size=1,
        seed=0,
        async_scheduling=False,
    ) as runner:
        llm = runner.get_llm()
        engine = llm.llm_engine
        scheduler = engine.engine_core.engine_core.scheduler
        assert scheduler.need_mamba_chunk_invariant_split
        vocab = engine.vllm_config.model_config.get_vocab_size()
        prompts = [
            TokensPrompt(
                prompt_token_ids=[
                    1 + (911 * 131 + i * 17 + k * 101) % (vocab - 1)
                    for i in range(length)
                ]
            )
            for k, length in enumerate([513, 514, 770])
        ]
        params = SamplingParams(
            temperature=0, max_tokens=64, ignore_eos=True, logprobs=5, seed=42
        )
        baseline = [
            _signature(llm.generate([prompt], params, use_tqdm=False)[0])
            for prompt in prompts
        ]
        mixed_steps = []
        original_schedule = scheduler.schedule

        def observe_schedule(*args, **kwargs):
            before = {
                key: (r.num_computed_tokens, r.num_prompt_tokens)
                for key, r in scheduler.requests.items()
            }
            output = original_schedule(*args, **kwargs)
            prompt = history = False
            for key, count in output.num_scheduled_tokens.items():
                computed, boundary = before[key]
                if count > 1:
                    prompt |= computed < boundary
                    history |= computed >= boundary
            mixed_steps.append(prompt and history)
            return output

        monkeypatch.setattr(scheduler, "schedule", observe_schedule)
        # Reuse the engine and request slots, with two preemptions per run.
        for repeat in range(2):
            mixed_steps.clear()
            requests = {}
            finals = {}
            resets = 0
            recovery_steps = None
            labels = {f"mixed-{repeat}-{k}": k for k in range(3)}

            def add(k, repeat=repeat, requests=requests):
                key = engine.add_request(f"mixed-{repeat}-{k}", prompts[k], params)
                requests[k] = scheduler.requests[key]

            add(0)
            add(1)
            for _ in range(1000):
                if not engine.has_unfinished_requests():
                    break
                for output in engine.step():
                    if output.finished:
                        finals[labels[output.request_id]] = _signature(output)
                if recovery_steps is not None:
                    recovery_steps += 1
                    if recovery_steps == 2 and 2 not in requests:
                        # Enter while earlier requests are rebuilding their
                        # prompt, so SSD and SSU replay coexist in a later step.
                        add(2)
                if resets < 2 and requests[0].num_output_tokens == (8, 31)[resets]:
                    live = [r for r in requests.values() if not r.is_finished()]
                    before = [(list(r.all_token_ids), r.num_preemptions) for r in live]
                    assert all(r.num_in_flight_tokens == 0 for r in live)
                    assert llm.reset_prefix_cache(reset_running_requests=True)
                    for request, (tokens, count) in zip(live, before):
                        assert request.num_computed_tokens == 0
                        assert request.num_preemptions == count + 1
                        assert list(request.all_token_ids) == tokens
                    resets += 1
                    recovery_steps = 0
            else:
                pytest.fail("Recovery made no bounded progress")
            assert resets == 2
            assert any(mixed_steps), "Test never mixed SSD prompt and SSU history"
            assert sorted(finals) == [0, 1, 2]
            for k in range(3):
                assert finals[k] == baseline[k], (repeat, k)


@pytest.mark.skipif(not current_platform.is_cuda(), reason="Requires CUDA")
@pytest.mark.timeout(600)
@pytest.mark.parametrize("enforce_eager", [True, False], ids=["eager", "compiled"])
@pytest.mark.parametrize("async_scheduling", [False, True], ids=["sync", "async"])
@pytest.mark.parametrize(
    "tensor_parallel_size",
    [1, pytest.param(2, marks=multi_gpu_marks(num_gpus=2))],
    ids=["tp1", "tp2"],
)
def test_mamba2_kv_pressure_preemption(
    vllm_runner, monkeypatch, enforce_eager, async_scheduling, tensor_parallel_size
):
    """Real allocation failures must preserve tokens and logprob bits on recovery."""
    if torch.cuda.device_count() < tensor_parallel_size:
        pytest.skip("Not enough GPUs for tensor parallelism")
    monkeypatch.setenv("VLLM_BATCH_INVARIANT", "1")
    monkeypatch.setenv("VLLM_ENABLE_V1_MULTIPROCESSING", "0")
    monkeypatch.setenv("VLLM_USE_FLASHINFER_SAMPLER", "0")
    model = os.getenv("VLLM_TEST_MODEL", "ibm-granite/granite-4.0-h-350m")
    with vllm_runner(
        model,
        dtype="bfloat16",
        enforce_eager=enforce_eager,
        max_model_len=1024,
        max_num_seqs=8,
        max_num_batched_tokens=1024,
        enable_chunked_prefill=True,
        enable_prefix_caching=False,
        mamba_ssm_cache_dtype="auto",
        gpu_memory_utilization=0.25,
        # Four initial requests fit, but extending attention KV past the first
        # page exhausts the pool. Do not mock allocation or call the reset API.
        num_gpu_blocks_override=33,
        tensor_parallel_size=tensor_parallel_size,
        seed=0,
        async_scheduling=async_scheduling,
    ) as runner:
        llm = runner.get_llm()
        engine = llm.llm_engine
        scheduler = engine.engine_core.engine_core.scheduler
        vocab = engine.vllm_config.model_config.get_vocab_size()
        prompts = [
            TokensPrompt(
                prompt_token_ids=[
                    1 + (911 * 131 + i * 17 + k * 101) % (vocab - 1)
                    for i in range(257 + k * 17)
                ]
            )
            for k in range(4)
        ]
        params = SamplingParams(
            temperature=0, max_tokens=160, ignore_eos=True, logprobs=5, seed=42
        )
        baseline = [
            _signature(llm.generate([prompt], params, use_tqdm=False)[0])
            for prompt in prompts
        ]
        history_preemptions = []
        original_preempt = scheduler._preempt_request

        def observe_preempt(request, *args, **kwargs):
            history_preemptions.append(request.num_output_tokens)
            return original_preempt(request, *args, **kwargs)

        monkeypatch.setattr(scheduler, "_preempt_request", observe_preempt)
        for repeat in range(2):
            history_preemptions.clear()
            for k, prompt in enumerate(prompts):
                engine.add_request(f"pressure-{repeat}-{k}", prompt, params)
            finals = {}
            for _ in range(1000):
                if not engine.has_unfinished_requests():
                    break
                for output in engine.step():
                    if output.finished:
                        finals[output.request_id] = _signature(output)
            else:
                pytest.fail("KV-pressure recovery made no bounded progress")
            assert any(n > 1 for n in history_preemptions), (
                "Test never preempted a request with generated history"
            )
            assert len(finals) == len(prompts)
            for k in range(len(prompts)):
                assert finals[f"pressure-{repeat}-{k}"] == baseline[k], (repeat, k)
