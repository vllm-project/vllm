"""Streaming content extraction for Kimi K3 must match the non-streaming
parser and never leak XTML control markers to the client.

The end-of-turn ``<|close|>message<|sep|>`` marker is generated by the model
right before the end-of-message token (see ``_K3_MESSAGE_CLOSE`` in
``structural_tag_registry``). ``extract_tool_calls`` strips it via
``_strip_response_content``; the streaming path has to hold it back too.
"""

from vllm.entrypoints.openai.chat_completion.protocol import (
    ChatCompletionRequest,
)
from vllm.tool_parsers.kimi_k3_tool_parser import KimiK3ToolParser

MESSAGE_CLOSE = "<|close|>message<|sep|>"


class _DummyTokenizer:
    def get_vocab(self):
        return {}

    def encode(self, text, add_special_tokens=False):
        return [ord(c) for c in text]


def _request() -> ChatCompletionRequest:
    return ChatCompletionRequest(
        model="k3", messages=[{"role": "user", "content": "hi"}]
    )


def _stream_content(model_output: str, chunk_size: int) -> str:
    parser = KimiK3ToolParser(_DummyTokenizer())
    request = _request()
    content = ""
    previous = ""
    for start in range(0, len(model_output), chunk_size):
        delta = model_output[start : start + chunk_size]
        current = previous + delta
        message = parser.extract_tool_calls_streaming(
            previous, current, delta, [], [], [], request
        )
        if message is not None and message.content:
            content += message.content
        previous = current
    return content


def test_streaming_content_stops_at_message_close():
    """A turn ending in <|close|>message<|sep|> with no response-close marker
    streams the same content the non-streaming parser extracts."""
    model_output = f"Hello{MESSAGE_CLOSE}"
    unary = KimiK3ToolParser(_DummyTokenizer()).extract_tool_calls(
        model_output, _request()
    )
    assert unary.content == "Hello"

    streamed = _stream_content(model_output, chunk_size=len(model_output))
    assert streamed == unary.content


def test_streaming_content_holds_split_message_close():
    """The marker must be held back even when deltas split it mid-token."""
    model_output = f"Hello{MESSAGE_CLOSE}"
    for chunk_size in (1, 3, 7):
        streamed = _stream_content(model_output, chunk_size)
        assert MESSAGE_CLOSE not in streamed, f"chunk_size={chunk_size}"
        assert streamed == "Hello", f"chunk_size={chunk_size}"
